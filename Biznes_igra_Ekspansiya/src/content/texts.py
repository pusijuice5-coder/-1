def starts():
    """время начала каждого блока от старта игры, 'ч:мм'"""
    out, t = [], 0
    for _, _, m in TIMING:
        out.append('%d:%02d' % (t // 60, t % 60))
        t += m
    return out, t


def example_year():
    """Пример для правил: четыре банка, один открывает офис на Севере и поднимает цифровые каналы."""
    state = G.new_state(4)
    dec = [dict(offices={'NORTH': 1}, up=['D'], policy='С')] + [dict(policy='С')] * 3
    r = G.play_year(state, dec, 1)[0]
    return r


def check():
    """Сверка чисел, которые в текстах написаны словами, с параметрами модели."""
    pc = lambda r, y: round(100 * (G.POOL[r][y - 1] / G.POOL[r][y - 2] - 1))
    assert (pc('SOUTH', 2), pc('VALLEY', 2), pc('NORTH', 2), pc('CAP', 2)) == (50, 20, 10, 0)
    assert G.POOL['SEZ'][1] / G.POOL['SEZ'][0] == 2.5 and G.POOL['SEZ'][2] / G.POOL['SEZ'][1] == 2.2
    assert (pc('SOUTH', 3), pc('VALLEY', 3), pc('CAP', 3), pc('NORTH', 3)) == (40, 11, 3, -32)
    assert (pc('VALLEY', 4), pc('SEZ', 4), pc('NORTH', 4), pc('SOUTH', 4), pc('CAP', 4)) == (-30, 36, 53, 19, 3)
    assert G.SHOCK['NORTH'][2] == 24 and G.SHOCK['VALLEY'][3] == 20
    e = G.EVENTS
    assert (e['inspection']['year'], e['inspection']['fine'], e['cyber']['year'], e['cyber']['loss'], e['talent']['year'], e['talent']['cut']) == (2, 20, 3, 30, 4, 0.10)
    p = G.P
    assert (p['open_cost'], p['upkeep'], p['capacity'], p['base_loss'], p['analytics'], p['start_budget']) == (25, 8, 45, 3, 8, 100)
    assert p['level_cost'] == {2: 20, 3: 30, 4: 40} and p['risk_cut'] == 0.25 and p['digital_save'] == 2 and p['service_gain'] == 0.2
    assert p['policy'] == {'О': (0.90, 0.5), 'С': (1.00, 1.0), 'А': (1.15, 1.6)}
    assert [p['span_base'] + p['span_step'] * k for k in (1, 2, 3, 4)] == [4, 6, 8, 10]
    r = example_year()
    assert abs(r['income'] - 82.5) < 1e-9 and r['upkeep'] == 18 and r['base_loss'] == 9 and abs(r['profit'] - 55.5) < 1e-9 and abs(r['budget_end'] - 110.5) < 1e-9
    assert sum(m for _, _, m in TIMING) == 235
    return True
