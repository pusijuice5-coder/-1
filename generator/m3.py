def smooth(vals, n=90):
    """Catmull-Rom interpolation of equally spaced values."""
    pts = []
    m = len(vals) - 1
    for k in range(n + 1):
        t = k / n * m
        i = min(int(t), m - 1)
        u = t - i
        p0 = vals[max(i - 1, 0)]; p1 = vals[i]; p2 = vals[i + 1]; p3 = vals[min(i + 2, m)]
        v = 0.5 * ((2 * p1) + (-p0 + p2) * u + (2 * p0 - 5 * p1 + 4 * p2 - p3) * u * u + (-p0 + 3 * p1 - 3 * p2 + p3) * u ** 3)
        pts.append((t / m, v))
    return pts


