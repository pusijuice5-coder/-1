# -*- coding: utf-8 -*-
import math
from tpl import *


def build(d):
    module_cover(d, 5, "Agile-культура и я",
                 ["Доверие и командная ответственность", "Психологическая безопасность и обратная связь",
                  "Agile-практики в вашей работе", "Как работать с agile-командами"],
                 "Заключительный модуль — о культуре и о вас. Любые практики работают только на фундаменте доверия. Мы поговорим о "
                 "психологической безопасности, обратной связи и о том, как применять Agile в своей работе, даже если вы не входите в "
                 "agile-команду.")

    # ---- culture & trust
    s = d.new(bg="video", notes=(
        "Agile-культура держится на командной ответственности, открытости и доверии. Идея одного человека развивается всей командой, а "
        "за результат команда отвечает вместе. Доверие можно описать формулой: открытость, профессионализм и надёжность, делённые на "
        "личный интерес. Чем больше человек ставит свою выгоду выше общей цели, тем ниже доверие к нему. Справа — soft skills, которые "
        "особенно важны в Agile: от самоорганизации и обратной связи до эмпатии и умения признавать ошибки."))
    s.title("Agile-культура: доверие и ответственность", anim=0)
    pts = ["Идея одного развивается всей командой", "Командная ответственность за результат — единая оценка для всей команды",
           "Открытая среда: кросс-функциональность, пространство и технологии"]
    for i, t in enumerate(pts):
        y = 1.35 + i * 0.92
        s.begin("Принцип %d" % (i + 1))
        s.rrect(0.55, y, 6.3, 0.78, r=0.39, fill=WHITE, shadow="soft")
        s.circle_num(0.65, y + 0.1, 0.58, i + 1, fill=DARK, sz=15)
        s.text(1.4, y + 0.04, 5.3, 0.7, t, sz=13.5, color=BODY, anchor="ctr", lnsp=1.0)
        s.end(anim=100 + i * 130)
    s.begin("Формула доверия")
    card(s, 0.55, 4.25, 6.3, 2.65, dark=True)
    s.text(0.85, 4.4, 5.7, 0.3, "ФОРМУЛА ДОВЕРИЯ", sz=11, bold=True, color=LIME)
    s.text(0.85, 4.8, 1.6, 1.2, "Доверие =", sz=18, bold=True, color=WHITE, anchor="ctr")
    s.text(2.45, 4.8, 4.2, 0.62, "Открытость + Профессионализм + Надёжность", sz=13.5, bold=True, color=WHITE, align="ctr", anchor="ctr", lnsp=1.0)
    s.line(2.55, 5.46, 6.55, 5.46, color=LIME, lw=2)
    s.text(2.45, 5.5, 4.2, 0.45, "Личный интерес", sz=13.5, bold=True, color=G4, align="ctr", anchor="ctr")
    s.text(0.85, 6.05, 5.75, 0.75, "Чем сильнее человек ставит свою выгоду выше общей цели, тем ниже доверие к нему — даже при высоком "
                                   "профессионализме.", sz=11.5, color="D8E8DC", lnsp=1.0)
    s.end(anim=500)
    skills = ["Постоянное совершенствование", "Фокус на результат", "Коллективная ответственность", "Психологическая безопасность",
              "Обратная связь", "Эмпатия", "Коллаборация", "Признание ошибок", "Самоорганизация"]
    cx, cy, rx, ry = 9.95, 4.2, 2.1, 2.3
    s.begin("Soft skills")
    for k in range(len(skills)):
        a = math.radians(k * 360 / len(skills))
        s.line(cx, cy, cx + rx * math.sin(a) * 0.8, cy - ry * math.cos(a) * 0.8, color=G4, lw=1.25)
    s.shape(cx - 0.85, cy - 0.85, 1.7, 1.7, geom="ellipse", fill=G2, shadow="green", text="Soft\nskills", sz=17, bold=True, color=WHITE,
            align="ctr", anchor="ctr", lnsp=1.0)
    from lib import _font
    for k, t in enumerate(skills):
        a = math.radians(k * 360 / len(skills))
        px, py = cx + rx * math.sin(a), cy - ry * math.cos(a)
        one = _font(11, True).getlength(t) / 720 + 0.3
        if one <= 1.95 or k == 0:
            w, h = one, 0.44
        else:
            w = 1.82
            h = text_height([{"runs": parse_runs(t)}], w - 0.16, 11, True, 0.95) + 0.14
        s.rrect(px - w / 2, py - h / 2, w, h, r=0.18, fill=WHITE, shadow="soft", text=t, sz=11, bold=True, color=DARK, align="ctr",
                anchor="ctr", inset=(0.08, 0, 0.08, 0), lnsp=0.95)
    s.end(anim=300)

    # ---- psychological safety & SBI
    s = d.new(bg="video", notes=(
        "Психологическая безопасность — это уверенность, что за вопрос, идею или признание ошибки тебя не накажут и не высмеют. Без неё о "
        "проблемах молчат до последнего. Её создают простые вещи: вместо поиска виноватых — вопрос, что улучшить в процессе. Вторая "
        "опора культуры — обратная связь. Удобно давать её по модели SBI: ситуация, поведение, влияние. Опишите, когда это было, что "
        "конкретно сделал человек, и к чему это привело. Так обратная связь становится конкретной и полезной."))
    s.title("Психологическая безопасность и обратная связь", anim=0)
    s.begin("Безопасность")
    card(s, 0.55, 1.35, 6.0, 5.55)
    s.text(0.85, 1.52, 5.4, 0.4, "Психологическая безопасность", sz=17, bold=True, color=TITLE)
    s.text(0.85, 2.0, 5.4, 0.75, "Уверенность, что за вопрос, идею или признание ошибки тебя не накажут и не высмеют.", sz=13.5,
           bold=True, color=G1, lnsp=1.05)
    s.text(0.85, 2.8, 5.4, 0.95, "**Почему это важно:** без неё о проблемах молчат до последнего — и узнают о них, когда исправлять уже дорого.",
           sz=12.5, color=BODY, lnsp=1.05)
    s.text(0.85, 3.85, 2.4, 0.3, "ВМЕСТО", sz=10, bold=True, color=MUTED)
    s.text(3.6, 3.85, 2.4, 0.3, "ЛУЧШЕ", sz=10, bold=True, color=G2)
    for i, (a, b) in enumerate([("«Кто виноват?»", "«Что улучшим в процессе?»"), ("«Это не мой вопрос»", "«Давай разберёмся вместе»"),
                                ("«Не задавай глупых вопросов»", "«Хороший вопрос, спасибо»")]):
        y = 4.25 + i * 0.82
        s.rrect(0.85, y, 2.45, 0.66, r=0.2, fill="EEF1EF", text=a, sz=11.5, color=MUTED, align="ctr", anchor="ctr", inset=(0.06, 0, 0.06, 0), lnsp=0.95)
        s.shape(3.33, y + 0.2, 0.25, 0.26, geom="chevron", fill=G2)
        s.rrect(3.62, y, 2.65, 0.66, r=0.2, fill="D7ECDB", text=b, sz=11.5, bold=True, color=DARK, align="ctr", anchor="ctr", inset=(0.06, 0, 0.06, 0), lnsp=0.95)
    s.end(anim=100)
    s.begin("SBI")
    card(s, 6.8, 1.35, 5.95, 5.55, dark=True)
    s.text(7.1, 1.52, 5.4, 0.4, "Обратная связь по модели SBI", sz=17, bold=True, color=LIME)
    for i, (l, t) in enumerate([("S", "**Ситуация** — когда и где это было"), ("B", "**Поведение** — что конкретно человек сделал — факты, без оценок"),
                                ("I", "**Влияние** — к чему это привело для команды, клиента, результата")]):
        y = 2.05 + i * 0.72
        s.circle_num(7.1, y + 0.04, 0.52, l, fill=LIME, color=DARK, sz=15)
        s.text(7.8, y, 4.75, 0.62, t, sz=12.5, color=WHITE, anchor="ctr", lnsp=1.0)
    s.text(7.1, 4.28, 5.4, 0.3, "ПРИМЕРЫ", sz=10, bold=True, color=G4)
    s.rrect(7.1, 4.6, 5.4, 1.08, r=0.16, fill=G1, text="«На вчерашнем обзоре (S) ты показал прототип на реальном сценарии обслуживания (B) — "
            "стейкхолдеры сразу поняли ценность и дали точные замечания (I)»", sz=11, color=WHITE, anchor="ctr", inset=(0.18, 0, 0.15, 0), lnsp=1.0)
    s.rrect(7.1, 5.78, 5.4, 0.95, r=0.16, fill="1E4A31", text="«На планировании (S) ты несколько раз перебил коллег (B) — часть идей не "
            "прозвучала, и мы не учли риск (I)»", sz=11, color=WHITE, anchor="ctr", inset=(0.18, 0, 0.15, 0), lnsp=1.0)
    s.end(anim=400)

    # ---- agile in your work
    s = d.new(bg="video", notes=(
        "Agile-практики полезны в любой работе, даже вне agile-команды. Начинайте с клиента: понимайте, кто он и какую проблему вы "
        "решаете. Показывайте результат рано — черновик через пару дней лучше идеала через месяц. Визуализируйте свою работу на простой "
        "доске. Приоритизируйте по ценности, а не по громкости запроса. Регулярно собирайте обратную связь. И раз в две недели проводите "
        "мини-ретроспективу: что получилось, что мешало, что изменим."))
    s.title("Agile в вашей работе — даже вне agile-команды", anim=0)
    tips = [("Начинайте с клиента", "Кто ваш клиент — внешний или внутренний? Какую его проблему вы решаете?"),
            ("Показывайте результат рано", "Черновик через два дня полезнее идеального документа через месяц."),
            ("Визуализируйте работу", "Простая доска «Нужно сделать — В работе — Готово» делает загрузку и узкие места видимыми."),
            ("Приоритизируйте по ценности", "Спрашивайте «что даст наибольший эффект?», а не «кто громче просит?»."),
            ("Собирайте обратную связь", "Регулярно спрашивайте коллег и клиентов, что работает, а что нет."),
            ("Проводите мини-ретро", "Раз в две недели: что получилось, что мешало, что изменим.")]
    for i, (h, t) in enumerate(tips):
        x = 0.55 + (i % 3) * 4.15
        y = 1.35 + (i // 3) * 2.8
        s.begin(h)
        card(s, x, y, 3.95, 2.6, dark=(i == 0))
        s.hexnum(x + 0.25, y + 0.28, 0.95, i + 1, fill=LIME if i == 0 else DARK, color=DARK if i == 0 else WHITE, sz=19)
        th = text_height([{"runs": parse_runs(h)}], 3.4, 16, True, 0.95)
        s.text(x + 0.3, y + 1.0, 3.4, th + 0.05, h, sz=16, bold=True, color=WHITE if i == 0 else TITLE, lnsp=0.95)
        s.text(x + 0.3, y + 1.12 + th, 3.4, 2.5 - 1.2 - th, t, sz=12.5, color="D8E8DC" if i == 0 else BODY, lnsp=1.05)
        s.end(anim=100 + i * 130)

    # ---- working with agile teams
    s = d.new(bg="video", notes=(
        "Даже если вы не в agile-команде, вы наверняка будете с ними работать — как клиент, эксперт или заказчик. Приходите на обзоры "
        "спринтов и давайте конкретную обратную связь. Все запросы передавайте Владельцу продукта, а не участникам команды напрямую. "
        "Описывайте проблему и потребность, а решение команда предложит сама. И будьте доступны как эксперт. Избегайте постановки задач "
        "в обход PO, требований изменить цель спринта на ходу и ожидания финальной сдачи."))
    section_title_light(s, "Как работать с agile-командами", "Для команды вы можете быть клиентом, экспертом или заказчиком")
    do = ["Приходите на обзор спринта и давайте конкретную обратную связь",
          "Передавайте запросы Владельцу продукта — он управляет приоритетами",
          "Описывайте проблему и потребность, а не готовое решение",
          "Будьте доступны как эксперт: риски, право, комплаенс, работа филиалов"]
    avoid = ["Ставить задачи участникам команды напрямую, в обход PO", "Требовать изменить цель спринта «на ходу»",
             "Просить подробные отчёты вместо демонстрации результата", "Ждать финальной сдачи, чтобы впервые посмотреть на продукт"]
    for j, (lab, items, dark) in enumerate([("ДЕЛАЙТЕ", do, True), ("ИЗБЕГАЙТЕ", avoid, False)]):
        x = 0.55 + j * 6.2
        s.begin(lab)
        card(s, x, 1.85, 6.0, 3.65, dark=dark)
        s.chip(x + 0.3, 2.05, 1.7, 0.4, lab, fill=LIME if dark else GREY, color=DARK, sz=11.5)
        for i, t in enumerate(items):
            y = 2.65 + i * 0.7
            if dark:
                check_icon(s, x + 0.3, y + 0.08, 0.42, fill=G2)
            else:
                cross_icon(s, x + 0.3, y + 0.08, 0.42)
            s.text(x + 0.9, y, 4.9, 0.6, t, sz=13, color=WHITE if dark else BODY, anchor="ctr", lnsp=1.0)
        s.end(anim=150 + j * 250)
    s.begin("Потребность")
    s.rrect(0.55, 5.75, 12.2, 1.15, r=0.25, fill=MINT)
    s.text(0.85, 5.85, 3.0, 0.95, "ПОТРЕБНОСТЬ ВМЕСТО РЕШЕНИЯ", sz=12, bold=True, color=G2, anchor="ctr", lnsp=1.0)
    s.text(3.85, 5.85, 8.7, 0.95, "Не «Добавьте кнопку выписки на главный экран», а **«Клиенты в филиале тратят 10 минут на поиск выписки — "
                                  "хотим сократить это время»**.", sz=13.5, color=DARK, anchor="ctr", lnsp=1.05)
    s.end(anim=700)

    opts = ["Промолчать — это не ваша команда и не ваша ответственность",
            "Сказать прямо на обзоре, описав ситуацию клиента и почему шаг неудобен",
            "После встречи написать жалобу руководителю команды",
            "После встречи попросить разработчика тихо переделать экран"]
    quiz(d, 5, "Вы — сотрудник филиала. Вас пригласили на обзор спринта, где команда показывает новый экран оформления вклада. Вы видите, "
               "что один из шагов будет неудобен клиентам.", "Что лучше сделать?", opts, 1)
    review(d, 5, opts,
           ["Обзор спринта и нужен, чтобы получить обратную связь от пользователей и стейкхолдеров.",
            "Конкретная обратная связь от тех, кто работает с клиентами, — самое ценное на демо. PO учтёт её в бэклоге.",
            "Обратная связь должна быть открытой и прямой, а не через эскалацию.",
            "Изменения — через бэклог и PO, иначе теряются прозрачность и фокус команды."], 1,
           "Верный ответ — Б. Обзор спринта существует именно для того, чтобы услышать тех, кто знает клиентов. Опишите ситуацию клиента "
           "конкретно — Владелец продукта учтёт это в бэклоге. Молчать, жаловаться или договариваться в обход — значит лишить команду "
           "ценной информации или нарушить прозрачность.")
    summary(d, 5, ["Доверие и психологическая безопасность — фундамент, на котором работают все agile-практики.",
                   "Обратная связь должна быть конкретной и своевременной: ситуация — поведение — влияние.",
                   "Agile полезен в любой работе: клиент в центре, короткие шаги, видимость работы и регулярные улучшения."],
            "Далее: итоги курса и итоговый тест",
            "Итоги пятого модуля. Доверие и психологическая безопасность — фундамент всех практик. Обратная связь должна быть конкретной: "
            "ситуация, поведение, влияние. А гибкие практики полезны в любой работе. Остались итоги курса и итоговый тест.")
