# -*- coding: utf-8 -*-
from tpl import *


def build(d):
    # ---- 12: second way (fills the user's empty slide 12, mirrors slide 11)
    s = d.new(bg="video", replace=12, notes=(
        "Второй способ — итеративный подход, или Agile. Продукт растёт небольшими порциями: каждые две–четыре недели "
        "появляется работающий результат, который можно показать клиентам и получить обратную связь. "
        "Обратная связь меняет план, пока это ещё дёшево."))
    s.text(0.31, 0.40, 9.36, 0.65, "Два способа создавать ценность", sz=36, bold=True, color="000000", anim=0)
    s.text(0.31, 1.14, 6.31, 0.83, "Второй способ\nИтеративный подход (Agile)", sz=24, bold=True, color="000000", lnsp=0.95, anim=100)
    s.pic("stand", 4.06, 0, 13.33, 7.5, crop=(0, 0, 0, 0), name="Рисунок 7")
    heights = [1.05, 1.7, 2.35, 3.0]
    cols = [G5, G3, G1, DARK]
    base = 6.05
    for i, (hh, c) in enumerate(zip(heights, cols)):
        x = 0.45 + i * 1.5
        s.begin("Итерация %d" % (i + 1))
        s.shape(x + 0.26, base - hh - 0.95, 0.78, 0.78, geom="ellipse", fill=WHITE, line=G2, lw=2,
                text="2 нед", sz=10, bold=True, color=DARK, align="ctr", anchor="ctr", inset=(0, 0, 0, 0))
        s.rrect(x, base - hh, 1.3, hh, r=0.12, fill=c, shadow="soft")
        s.text(x, base - 0.5, 1.3, 0.4, "Итерация %d" % (i + 1), sz=11, bold=True, color=WHITE, align="ctr", anchor="ctr")
        s.end(anim=200 + i * 250)
    s.line(0.45, 6.18, 6.25, 6.18, color=G2, lw=2, tail="triangle")
    s.text(0.54, 6.54, 7.9, 0.75, "Работающий результат каждые 2–4 недели. Обратная связь меняет план, пока это дёшево.",
           sz=16, color=BODY, anim=1300)

    # ---- 13: when to use what
    def cards(s, ytop):
        y = max(ytop + 0.35, 3.9)
        for i, (h, t) in enumerate([("Каскад", "если требования известны и стабильны"),
                                    ("Agile", "если много неизвестных и важна быстрая обратная связь")]):
            s.begin("Когда " + h)
            s.rrect(0.7, y + i * 1.25, 5.7, 1.05, r=0.22, fill=DARK, shadow="green")
            s.chip(0.95, y + i * 1.25 + 0.33, 1.25, 0.4, h, fill=LIME if i else GREY, color=DARK, sz=12)
            s.text(2.4, y + i * 1.25 + 0.08, 3.85, 0.9, t, sz=14, color=WHITE, anchor="ctr")
            s.end(anim=500 + i * 250)
    talk(d, "Каскад не плох сам по себе.\nОн хорош там, где всё известно заранее. А Agile выигрывает, когда неизвестного много.",
         notes=("Каскадный подход не плох сам по себе — он хорош, когда требования известны и стабильны. "
                "Agile выигрывает там, где много неизвестного и важна быстрая обратная связь от клиентов."),
         pose="present", extra=cards)

    # ---- 14: Agile is...
    s = d.new(bg="video", notes=(
        "Agile — это прежде всего образ мышления. Он описан в четырёх ценностях, определён двенадцатью принципами и "
        "распространяется через множество практик: Scrum, Kanban, Lean и другие. Практики — самая заметная часть, но у них "
        "меньше всего силы. Если команда проводит все встречи по Scrum, но не разделяет ценностей Agile, результата не будет."))
    s.title("Agile — это…", anim=0)
    s.text(0.55, 1.2, 12.2, 0.95, "…подход к развитию продукта для быстрой и регулярной поставки функционала, которым клиент может "
           "пользоваться сразу, регулярного сбора обратной связи и работы в условиях риска и неопределённости.",
           sz=16, color=BODY, lnsp=1.05, anim=100)
    steps = [("Agile — это", "образ мышления", DARK, WHITE, 1.75),
             ("описанный в", "4 ценностях", G1, WHITE, 2.25),
             ("определённый", "12 принципами", G2, WHITE, 2.75),
             ("распространяемый через", "множество практик", G4, DARK, 3.25)]
    base = 5.75
    for i, (a, b, c, tc, hh) in enumerate(steps):
        x = 0.55 + i * 3.1
        s.begin("Слой %d" % (i + 1))
        s.rrect(x, base - hh, 2.9, hh, r=0.2, fill=c, shadow="soft")
        s.text(x + 0.22, base - hh + 0.22, 2.5, 0.35, a, sz=13, color=tc)
        s.text(x + 0.22, base - hh + 0.55, 2.5, 0.85, b, sz=20, bold=True, color=tc, lnsp=0.95)
        if i == 3:
            s.text(x + 0.22, base - 1.25, 2.5, 1.0, "Scrum · Kanban · Lean\nXP · FDD", sz=13, bold=True, color=DARK)
        s.end(anim=250 + i * 200)
    s.line(0.6, 5.98, 12.7, 5.98, color=G2, lw=1.75, head="triangle", tail="triangle")
    s.text(0.55, 6.05, 5.5, 0.35, "более мощные, менее видимые", sz=12, color=MUTED, anim=1100)
    s.text(7.25, 6.05, 5.5, 0.35, "менее мощные, более видимые", sz=12, color=MUTED, align="r", anim=1100)
    s.text(0.55, 6.55, 12.2, 0.6, "Agile — это не столько про процесс работы, сколько про мышление сотрудников и их отношение к работе",
           sz=15, bold=True, color=G1, anim=1300)

    # ---- 15: 4 values
    s = d.new(bg="video", notes=(
        "В 2001 году семнадцать специалистов по разработке сформулировали Agile-манифест. В его основе — четыре ценности. "
        "Люди и взаимодействие важнее процессов и инструментов. Работающий продукт важнее исчерпывающей документации. "
        "Сотрудничество с заказчиком важнее согласования условий контракта. Готовность к изменениям важнее следования "
        "первоначальному плану. Манифест не отрицает процессы, документы, контракты и планы — он расставляет приоритеты."))
    section_title_light(s, "4 ценности Agile-манифеста", "Сформулированы в 2001 году авторами Agile-манифеста")
    vals = [("Люди и взаимодействие", "Процессы и инструменты"),
            ("Работающий продукт", "Исчерпывающая документация"),
            ("Сотрудничество с заказчиком", "Согласование условий контракта"),
            ("Готовность к изменениям", "Следование первоначальному плану")]
    for i, (top, bot) in enumerate(vals):
        x = 0.55 + i * 3.1
        s.begin("Ценность %d" % (i + 1))
        s.rrect(x, 2.0, 2.9, 1.75, r=0.22, fill=DARK, shadow="green")
        s.text(x + 0.2, 2.0, 2.5, 1.75, top, sz=18, bold=True, color=WHITE, align="ctr", anchor="ctr", lnsp=1.0)
        s.chip(x + 0.6, 3.98, 1.7, 0.42, "важнее, чем", fill=LIME, color=DARK, sz=12)
        s.rrect(x, 4.62, 2.9, 1.3, r=0.22, fill=WHITE, shadow="soft")
        s.text(x + 0.2, 4.62, 2.5, 1.3, bot, sz=15, color=MUTED, align="ctr", anchor="ctr", lnsp=1.0)
        s.end(anim=200 + i * 180)
    s.text(0.55, 6.3, 12.2, 0.5, "Не отрицая важности того, что снизу, мы всё-таки больше ценим то, что сверху",
           sz=15, bold=True, color=G1, align="ctr", anim=1000)

    # ---- 16: values in the bank
    s = d.new(bg="video", notes=(
        "Как эти ценности выглядят в жизни банка? Вместо длинной переписки между департаментами — короткая встреча нужных людей. "
        "Вместо объёмного ТЗ — прототип, который можно показать клиентам уже через неделю. Вместо финальной сдачи — регулярные "
        "демонстрации, на которые приходят сотрудники филиалов. А изменение требований — повод пересобрать приоритеты к "
        "следующему спринту, а не переписывать годовой план. Примеры условные, но они хорошо показывают разницу."))
    s.title("Как ценности выглядят в банке", anim=0)
    ex = [("Люди и взаимодействие", "цепочка из 20 писем между департаментами", "15-минутная встреча с юристом и риск-менеджером — вопрос закрыт"),
          ("Работающий продукт", "техническое задание на 60 страниц", "кликабельный прототип экрана, который через неделю видят клиенты"),
          ("Сотрудничество с заказчиком", "бизнес впервые видит результат на финальной сдаче", "сотрудники филиалов приходят на демонстрацию каждые 2 недели"),
          ("Готовность к изменениям", "новое требование = пересогласование годового плана", "команда пересобирает приоритеты к следующему спринту")]
    for i, (h, was, now) in enumerate(ex):
        x = 0.55 + (i % 2) * 6.2
        y = 1.35 + (i // 2) * 2.62
        s.begin("Пример %d" % (i + 1))
        s.rrect(x, y, 6.0, 2.4, r=0.22, fill=WHITE, shadow="soft")
        s.hexnum(x + 0.25, y + 0.22, 0.7, i + 1, fill=DARK, sz=14)
        s.text(x + 1.15, y + 0.22, 4.7, 0.47, h, sz=17, bold=True, color=TITLE, anchor="ctr")
        s.chip(x + 0.3, y + 0.98, 1.05, 0.34, "БЫЛО", fill=GREY, color=DARK, sz=10)
        s.text(x + 1.55, y + 0.9, 4.25, 0.55, was, sz=13, color=MUTED, anchor="ctr")
        s.chip(x + 0.3, y + 1.68, 1.05, 0.34, "СТАЛО", fill=G2, color=WHITE, sz=10)
        s.text(x + 1.55, y + 1.52, 4.25, 0.72, now, sz=13, bold=True, color=DARK, anchor="ctr")
        s.end(anim=150 + i * 180)

    # ---- 17: 12 principles
    s = d.new(bg="video", notes=(
        "Двенадцать принципов раскрывают ценности подробнее. Для удобства мы сгруппировали их по смыслу. Первая группа — о клиенте "
        "и ценности: поставлять работающий продукт рано и часто. Вторая — об изменениях и простоте: изменения приветствуются, а "
        "лишняя работа не нужна. Третья — о людях: бизнес и команда работают вместе, общаются лично, им доверяют. "
        "Четвёртая — о качестве и постоянном улучшении."))
    section_title_light(s, "12 принципов Agile-манифеста", "Сгруппированы по смыслу")
    groups = [("Клиент и ценность", [(1, "Главный приоритет — удовлетворение клиента за счёт ранней и регулярной поставки ценности"),
                                      (3, "Выпускать работающий продукт как можно чаще — от пары недель до пары месяцев"),
                                      (7, "Работающий продукт — основной показатель прогресса")]),
              ("Изменения и простота", [(2, "Изменения требований приветствуются даже на поздних стадиях — это конкурентное преимущество"),
                                        (10, "Простота — искусство не делать лишней работы — крайне необходима")]),
              ("Люди и команда", [(4, "Бизнес и разработчики работают вместе ежедневно"),
                                  (5, "Над продуктом работают мотивированные профессионалы: создайте условия и доверьтесь им"),
                                  (6, "Личное общение — самый эффективный способ обмена информацией"),
                                  (11, "Лучшие решения рождаются в самоорганизующихся командах")]),
              ("Качество и развитие", [(8, "Устойчивый ритм работы, который можно поддерживать бесконечно"),
                                       (9, "Постоянное внимание к техническому совершенству и качеству проектирования"),
                                       (12, "Команда регулярно анализирует свою работу и улучшает её")])]
    for gi, (gname, items) in enumerate(groups):
        x = 0.55 + gi * 3.1
        s.begin(gname)
        s.rrect(x, 1.8, 2.95, 0.6, r=0.2, fill=DARK, text=gname, sz=14, bold=True, color=WHITE, align="ctr", anchor="ctr")
        y = 2.55
        for num, t in items:
            th = text_height([{"runs": parse_runs(t)}], 2.2, 11.5, False, 1.0) + 0.3
            hh = max(0.72, th)
            s.rrect(x, y, 2.95, hh, r=0.16, fill=WHITE, shadow="soft")
            s.circle_num(x + 0.12, y + 0.14, 0.42, num, fill=G2 if gi % 2 == 0 else G1, sz=11)
            s.text(x + 0.64, y + 0.1, 2.2, hh - 0.2, t, sz=11.5, color=BODY, anchor="ctr", lnsp=1.0)
            y += hh + 0.12
        s.end(anim=150 + gi * 180)

    # ---- 18: myths intro
    talk(d, "Вокруг Agile много мифов.\nДавайте разберёмся, где миф, а где факт!", pose="chest",
         notes="Вокруг Agile много мифов. Давайте разберёмся, что из этого правда, а что нет.")

    # ---- 19: myths & facts
    s = d.new(bg="video", notes=(
        "Agile не только для IT — подходы эффективны в любых бизнес-направлениях. В Agile есть планы, просто планируют чаще и короче. "
        "Документация нужна — ровно в том объёме, который приносит пользу, а регуляторные требования никто не отменял. "
        "Agile — не хаос: зоны ответственности чётко распределены. И Scrum — это лишь один из фреймворков, а не синоним Agile."))
    s.title("Мифы и факты об Agile", anim=0)
    myths = [("«Agile — только для IT»", "Подходы работают в любых направлениях банка: от продуктов для клиентов до HR и обучения."),
             ("«В Agile нет планов»", "Планируют чаще и короче: цель спринта, квартальные цели, дорожная карта продукта."),
             ("«Документация не нужна»", "Документов ровно столько, сколько приносит пользу. Регуляторные требования никто не отменял."),
             ("«Agile — это хаос без ответственности»", "Ответственность чёткая: Владелец продукта отвечает за «что», команда — за «как» и качество."),
             ("«Agile и Scrum — одно и то же»", "Scrum — один из фреймворков. Есть Kanban, Lean и другие практики.")]
    for i, (m, f) in enumerate(myths):
        y = 1.35 + i * 1.03
        s.begin("Миф %d" % (i + 1))
        s.rrect(0.55, y, 12.2, 0.86, r=0.3, fill=WHITE, shadow="soft")
        s.chip(0.8, y + 0.25, 0.85, 0.36, "МИФ", fill=GREY, color=DARK, sz=10)
        s.text(1.85, y + 0.05, 3.9, 0.76, m, sz=14, bold=True, color=TITLE, anchor="ctr", lnsp=1.0)
        s.shape(5.85, y + 0.27, 0.42, 0.32, geom="chevron", fill=G2)
        s.chip(6.5, y + 0.25, 0.95, 0.36, "ФАКТ", fill=G2, color=WHITE, sz=10)
        s.text(7.62, y + 0.05, 4.95, 0.76, f, sz=12.5, color=BODY, anchor="ctr", lnsp=1.0)
        s.end(anim=150 + i * 170)

    # ---- 20/21: check yourself
    opts = ["Исчерпывающая документация: написать ТЗ ещё подробнее",
            "Сотрудничество с заказчиком: вовлекать пользователей с первых недель",
            "Следование плану: строже соблюдать утверждённое ТЗ",
            "Процессы и инструменты: внедрить систему согласования требований"]
    quiz(d, 1, "Команда два месяца готовила подробное ТЗ на новый сервис. На первой же демонстрации сотрудники филиала сказали, "
               "что клиентам нужно совсем другое.",
         "Какая ценность Agile помогла бы избежать этой ситуации?", opts, 1)
    review(d, 1, opts,
           ["Более подробное ТЗ не проверяет идею на пользователях — ошибка обнаружилась бы так же поздно.",
            "Ранняя и регулярная обратная связь от пользователей позволяет скорректировать курс, пока это дёшево.",
            "Строгое следование плану привело бы к запуску продукта, который не нужен клиентам.",
            "Ещё один процесс согласования не заменит живого диалога с пользователями."], 1,
           "Верный ответ — Б, сотрудничество с заказчиком. Если бы пользователи участвовали в работе с первых недель, команда "
           "узнала бы о проблеме сразу, а не через два месяца. Остальные варианты предлагают усилить то, что манифест ценит "
           "меньше, — документацию, план и процессы.")

    # ---- 22: summary
    summary(d, 1, ["Agile — это образ мышления: сначала 4 ценности и 12 принципов, а уже потом — практики вроде Scrum и Kanban.",
                   "Главная идея — поставлять ценность небольшими шагами и учиться на обратной связи клиентов.",
                   "Agile не отменяет планы, документы и ответственность — он делает их полезнее."],
            "Далее: Модуль 2. Agile-организация и команды",
            "Подведём итоги первого модуля. Agile — это образ мышления, а не набор встреч. Его суть — ценность небольшими шагами "
            "и обучение на обратной связи. И Agile не отменяет планы, документы и ответственность. Переходим ко второму модулю — "
            "об устройстве agile-организации и команд.")
