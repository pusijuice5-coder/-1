    s.title("Ключевые роли", anim=0)
    roles = [("PO", "Владелец продукта", "Product Owner", ["Отвечает за «ЧТО» делаем и зачем", "Формирует и приоритизирует бэклог",
                                                           "Отвечает за метрики и P&L; один на продукт"]),
             ("SM", "Скрам-мастер", "Scrum Master", ["Отвечает за процесс работы команды", "Фасилитирует события, убирает препятствия",
                                                     "Развивает agile-культуру, обучает, коучит"]),
             ("TM", "Участник команды", "Team member", ["Отвечает за «КАК» делаем и качество", "Создаёт инкремент продукта",
                                                        "Отвечает за сроки и цели команды"])]
    for i, (ab, nm, en, items) in enumerate(roles):
        x = 0.55 + i * 4.15
        s.begin(nm)
        card(s, x, 1.35, 3.95, 3.2)
        s.hexnum(x + 0.22, 1.55, 1.0, ab, fill=DARK, sz=17)
        s.text(x + 1.35, 1.58, 2.5, 0.4, nm, sz=16, bold=True, color=TITLE)
        s.text(x + 1.35, 1.98, 2.5, 0.3, en, sz=11, color=MUTED)
        bullets(s, x + 0.3, 2.45, 3.45, 2.0, items, sz=13.5, spc=6)
        s.end(anim=150 + i * 150)
