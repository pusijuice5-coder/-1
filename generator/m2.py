        "бэклог, расставляет приоритеты, отвечает за метрики продукта. Скрам-мастер отвечает за процесс: организует работу по "
        "Scrum, помогает убирать препятствия и развивает agile-культуру. Участники команды отвечают за то, как делать, за "
        "качество и сроки. Лидер компетенций развивает экспертизу сотрудников, но не руководит их работой в команде. А "
