        card(s, x, y, 4.0, 2.6)
        s.hexnum(x + 0.25, y + 0.28, 0.9, i + 1, fill=DARK, sz=18)
        s.text(x + 0.3, y + 1.0, 3.45, 0.7, h, sz=16, bold=True, color=TITLE, lnsp=1.0)
        s.text(x + 0.3, y + 1.68, 3.45, 0.85, t, sz=12.5, color=BODY, lnsp=1.0)
