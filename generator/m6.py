def test_q(d, n, q, options, correct, expl):
    total = len(QUESTIONS)
    s = d.new(bg="video", notes="Итоговый тест, вопрос %d из %d. %s Правильный ответ: %s — %s. %s" % (
        n, total, q, LETTERS[correct], options[correct], expl))
    s.ezoza("stand", right=13.1, h=6.9)
    s.begin("Прогресс")
    s.chip(0.55, 0.45, 2.05, 0.42, "ИТОГОВЫЙ ТЕСТ", fill=DARK, sz=11)
    s.text(2.8, 0.45, 3.0, 0.42, "Вопрос %d из %d" % (n, total), sz=14, bold=True, color=G1, anchor="ctr")
    for k in range(total):
        s.rrect(0.55 + k * 0.69, 1.05, 0.6, 0.12, r=0.06, fill=G2 if k < n else GREY)
    s.end(anim=0)
    qh = text_height([{"runs": parse_runs(q)}], 8.25, 24, True, 1.0)
    s.text(0.55, 1.5, 8.25, qh + 0.1, q, sz=24, bold=True, color=TITLE, lnsp=1.0, anim=100)
    y = max(2.75, 1.5 + qh + 0.45)
    oh = 0.78
    for i, opt in enumerate(options):
        s.begin("Вариант " + LETTERS[i])
        s.rrect(0.55, y, 8.25, oh, r=0.39, grad="button", shadow="pill")
        s.circle_num(0.67, y + 0.12, 0.54, LETTERS[i], fill=DARK, sz=15)
        s.text(1.45, y + 0.04, 7.15, oh - 0.08, opt, sz=15, color="1B2A22", anchor="ctr", lnsp=1.0)
        s.end(anim=250 + i * 120)
        y += oh + 0.2
    s.text(0.55, y + 0.05, 8.25, 0.35, "Выберите один вариант ответа.", sz=12, color=MUTED, anim=800)
    return s


