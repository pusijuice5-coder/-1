def module3(d):
    module_cover(d, 3, "Мошеннические схемы против клиентов",
                 "Схем двенадцать, а приёмы одни: страх, спешка, доверие и жадность",
                 ["Мошенник давит на 4 «кнопки», чтобы получить код или перевод",
                  "Видов фрода девять, а цель у них одна",
                  "12 схем: как работает, что вы видите, что объяснить клиенту"], "m3_phone.png")

    # 3.1
    s, y0 = light(d, "3.1 Как действуют мошенники: социальная инженерия", "Модуль 3 · Мошеннические схемы против клиентов",
                  "Мошенники давят на 4 «кнопки»: страх, спешку, доверие и жадность")
    t0 = "**Социальная инженерия (Social Engineering)** — это не взлом компьютера, а **обман человека**: использование психологии."
    s.begin("Определение")
    tile(s, X0, y0, 0.46, "venetian-mask")
    s.text(X0 + 0.66, y0 + 0.02, CW - 0.66, 0.5, t0, sz=14, color=BODY, bcolor=INK, lnsp=1.08)
    s.end(anim=0)
    y = y0 + 0.7
    s.text(X0, y, 8, 0.3, "Мошенники всегда нажимают на 4 «кнопки»:", sz=14, bold=True, color=INK, anim=100)
    btn = [("Страх", "«с вашей карты списываются деньги», «вы подозреваемый по уголовному делу»;", "siren"),
           ("Спешка", "«если не сделаете сейчас, потеряете деньги»;", "timer"),
           ("Доверие", "представляются сотрудником банка, МВД, СГБ, прокуратуры или родственником;", "badge-check"),
           ("Жадность", "«гарантированный высокий доход», «выигрыш», «приз».", "gift")]
    yc = y + 0.4
    gap = 0.2
    cw = (CW - 3 * gap) / 4
    tw = cw - 0.44
    ch = max(0.2 + 0.52 + 0.12 + h_of(b, tw, 13, False, 1.08) + 0.2 for _, b, _ in btn)
    for i, (t, b, ic) in enumerate(btn):
        cx = X0 + i * (cw + gap)
        s.begin("Кнопка " + t)
        s.rrect(cx, yc, cw, ch, r=0.2, fill=CARD)
        s.shape(cx + 0.22, yc + 0.22, 0.52, 0.52, geom="ellipse", fill=STOP_L, shadow="red", name="Кнопка")
        s.icon(ic, cx + 0.34, yc + 0.34, 0.28, color=WHITE)
        s.text(cx + 0.88, yc + 0.22, tw - 0.66, 0.52, t, sz=17, bold=True, color=INK, anchor="ctr")
        s.text(cx + 0.22, yc + 0.84, tw, ch - 0.96, b, sz=13, color=BODY, lnsp=1.08)
        s.end(anim=250 + i * 180, effect="zoom")
    y = yc + ch + 0.22
    hw = (CW - 0.25) / 2
    goal = "Цель почти всегда одна: получить у клиента **SMS-код, PIN, CVV** или заставить клиента **самого перевести** деньги."
    imp = ("Если клиент взволнован, торопится или напуган — возможно, на эти «кнопки» уже нажали. Именно в этот момент ваш "
           "спокойный разговор может остановить клиента.")
    gh = max(h_of(goal, hw - 1.12, 14, False, 1.08) + 0.5, h_of(imp, hw - 0.9, 13, False, 1.08) + 0.74)
    s.begin("Цель")
    s.rrect(X0, y, hw, gh, r=0.18, fill=GREEN, shadow="glow")
    tile(s, X0 + 0.25, y + 0.25, 0.5, "target", fill=LIME, color=GREEN)
    s.text(X0 + 0.95, y + 0.25, hw - 1.12, gh - 0.45, goal, sz=14, color=WHITE, bcolor=LIME, lnsp=1.08)
    s.end(anim=1000)
    yb = frame(s, "warn", X0 + hw + 0.25, y, hw, imp, lab="Важно", h=gh, sz=13, anim=1150)
    bottom(s, yb)

    # 3.2
    s, y0 = light(d, "3.2 Основные виды фрода", "Модуль 3 · Мошеннические схемы против клиентов",
                  "Видов фрода девять, а цель одна — коды клиента или его перевод")
    kinds = [("Фишинг (Phishing)", "Получение данных карты и пароля через поддельный сайт или ссылку", "link"),
             ("Вишинг (Vishing)", "Обман по телефону — например, от имени «службы безопасности банка»", "phone-call"),
             ("Смишинг (Smishing)", "Обман через SMS — «ваша карта заблокирована, перейдите по ссылке»", "message-square-text"),
             ("Кардинг (Carding)", "Несанкционированное использование украденных реквизитов карты в интернете", "credit-card"),
             ("Захват аккаунта (ATO)", "Мошенник получает управление аккаунтом мобильного банка клиента", "user-x"),
             ("SIM-своп (SIM Swap)", "Перевыпуск номера телефона клиента, чтобы получать его SMS-коды", "card-sim"),
             ("Вредоносная программа (APK, RAT)", "Установка на телефон вредоносной программы или программы удалённого управления", "bug"),
             ("APP-фрод", "Клиент, будучи обманутым, сам переводит деньги мошеннику", "hand-coins"),
             ("Дипфейк (Deepfake)", "Подделка голоса/видео близкого человека или руководителя с помощью искусственного интеллекта", "venetian-mask")]
    gap = 0.12
    cw = (CW - 2 * gap) / 3
    tw = cw - 0.18 - 0.38 - 0.14 - 0.16
    dw = cw - 0.36
    ch = max(0.15 + max(0.38, h_of(t, tw, 12.5, True, 1.04)) + 0.07 + h_of(b, dw, 12, False, 1.04) + 0.15 for t, b, _ in kinds)
    for i, (t, b, ic) in enumerate(kinds):
        cx = X0 + (i % 3) * (cw + gap)
        cy = y0 + (i // 3) * (ch + gap)
        s.begin(t)
        s.rrect(cx, cy, cw, ch, r=0.16, fill=CARD)
        th = max(0.38, h_of(t, tw, 12.5, True, 1.04))
        tile(s, cx + 0.18, cy + 0.15 + (th - 0.38) / 2, 0.38, ic)
        s.text(cx + 0.7, cy + 0.15, tw, th, t, sz=12.5, bold=True, color=INK, lnsp=1.04, anchor="ctr")
        s.text(cx + 0.18, cy + 0.22 + th, dw, ch - th - 0.34, b, sz=12, color=BODY, lnsp=1.04)
        s.end(anim=100 + i * 90)
    y = y0 + 3 * ch + 2 * gap + 0.16
    s.begin("Структура схем")
    lead = "На следующих слайдах каждая схема дана в одной структуре:"
    s.text(X0, y, CW, 0.28, lead, sz=12.5, color=BODY, check=False)
    y += 0.34
    x = X0
    for k, (t, f, c) in enumerate([("как работает", GREEN, WHITE), ("что вы видите в филиале", SIT_F, SIT_D), ("что объяснить клиенту", ADV_F, ADV_D)]):
        w = chip_w(t, 11.5, padx=0.14)
        chip(s, x, y, w, 0.42, t, fill=f, color=c, sz=11.5, line=None if k == 0 else (SIT_L if k == 1 else ADV_L))
        x += w
        if k < 2:
            s.icon("arrow-right", x + 0.05, y + 0.1, 0.22, color=GREEN, stroke=2.5)
            x += 0.32
    if x > X1 + 0.01:
        WARN.append("slide %d: legend too wide %.2f" % (s.no, x))
    s.end(anim=1000)
    bottom(s, y + 0.42)
    for k, sch in enumerate(SCHEMES):
        scheme(d, k, *sch)


def scheme(d, k, name, icon, title, how, see, tell):
    s, y0 = light(d, "3.%d %s" % (k + 3, name), "Модуль 3 · Схема %d из 12 · %s" % (k + 1, name), title)
    y = frame(s, "how", X0, y0, CW, how, lab="Как работает", icon=icon, sz=14, anim=100)
    y += 0.22
    hw = (CW - 0.25) / 2
    tw = hw - 0.26 * 2 - 0.46 - 0.2 - 0.2
    hs = [0.26 + 0.3 + h_of([{"t": t} for t in L], tw, 13.5, False, 1.08, 5) + 0.24 for L in (see, tell)]
    h = max(hs)
    frame(s, "see", X0, y, hw, see, lab="Что вы видите в филиале", items=True, h=h, sz=13.5, anim=350)
    yb = frame(s, "advice", X0 + hw + 0.25, y, hw, tell, lab="Что объяснить клиенту", items=True, h=h, sz=13.5, anim=600)
    bottom(s, yb)
