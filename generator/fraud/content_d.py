def situation(d, k, name, sit, lesson, ans):
    title = "Ситуация %d. %s" % (k + 1, name)
    s, y0 = light(d, "7.%d %s" % (k + 1, name), "Модуль 7 · Практическая ситуация %d из 7" % (k + 1), title)
    lw = 5.25
    rx, rw = X0 + lw + 0.3, CW - lw - 0.3
    # situation (grey frame) with the question
    tw = lw - 0.26 * 2 - 0.46 - 0.2
    sh = 0.26 + 0.3 + h_of(sit, tw, 15, False, 1.12) + 0.3
    s.begin("Ситуация")
    s.rrect(X0, y0, lw, sh, r=0.18, fill=SIT_F, line=SIT_L, lw=1.25)
    tile(s, X0 + 0.26, y0 + 0.24, 0.46, "store", fill=SIT_D)
    label(s, X0 + 0.92, y0 + 0.24, tw, "Ситуация. Что вы сделаете?", color=SIT_D)
    s.text(X0 + 0.92, y0 + 0.56, tw, sh - 0.7, sit, sz=15, color=INK, lnsp=1.12)
    s.end(anim=100)
    # thinking prompt + button
    by = y0 + sh + 0.3
    s.begin("Подсказка")
    s.icon("lightbulb", X0, by + 0.02, 0.34, color=GREEN)
    s.text(X0 + 0.48, by, lw - 0.5, 0.4, "Подумайте, что бы сделали вы, и нажмите кнопку", sz=13, color=MUTED, anchor="ctr")
    s.end(anim=400)
    btn = s.rrect(X0, by + 0.6, 3.7, 0.72, r=0.36, fill=GREEN, shadow="glow", text="Правильное действие  →", sz=17, bold=True,
                  color=WHITE, align="ctr", anchor="ctr", check=False, name="Кнопка Правильное действие", anim=550, effect="zoom")
    # answer (green frame), revealed on click
    atw = rw - 0.3 * 2 - 0.5 - 0.22
    ah = 0.3 + 0.3 + h_of(lesson, atw, 17, True, 1.08) + 0.14 + h_of(ans, atw, 14, False, 1.1) + 0.32
    s.begin("Правильное действие")
    s.rrect(rx, y0, rw, ah, r=0.2, fill=ADV_F, line=ADV_L, lw=1.5, shadow="soft")
    tile(s, rx + 0.3, y0 + 0.3, 0.5, "circle-check-big", fill=ADV_D)
    label(s, rx + 1.02, y0 + 0.3, atw, "Правильное действие", color=ADV_D)
    lh = h_of(lesson, atw, 17, True, 1.08)
    s.text(rx + 1.02, y0 + 0.6, atw, lh + 0.04, lesson, sz=17, bold=True, color=INK, lnsp=1.08)
    s.text(rx + 1.02, y0 + 0.74 + lh, atw, ah - 0.9 - lh, ans, sz=14, color=BODY, lnsp=1.1)
    gid = s.end()
    s.trigger(btn, [(gid, "grp", "rise", 0)])
    bottom(s, max(y0 + ah, by + 1.32))


