# -*- coding: utf-8 -*-
"""Module 4. Calendar: the window, appointment vs meeting, a meeting step by step, scheduling assistant, replies, changes, sharing."""
from kit import *
import mock

CAL = ["Создать", "Вид", "Расписание", "Календари"]
STEPS = ["Название", "Участники", "Время", "Место", "Повестка", "Отправить"]


def build(k):
    k.mod = 3
    opener(k, "m4-open", "04", "Календарь",
           "Встречи без долгой переписки «а когда вам удобно?».",
           ["Как устроено окно календаря", "Чем встреча отличается от собрания",
            "Как пригласить коллег и выбрать время, удобное всем", "Как отвечать на приглашения"],
           obj("i_calendar"), "≈ 9 минут",
           notes="Модуль четвёртый. Календарь. Вы узнаете, как устроено окно календаря, чем встреча отличается от собрания, "
                 "как выбрать время, удобное всем, и как отвечать на приглашения.")

    # ------------------------------------------------------------------ calendar window (morph tour)
    T = "Окно календаря"
    data = [
        ("new", "Две кнопки создания", "«Создать встречу» — событие только для вас. «Создать собрание» — встреча с приглашением коллег.", "Ctrl + 2 — открыть календарь",
         "Откройте календарь значком в левом нижнем углу или клавишами Контрол и два. На ленте — две главные кнопки: «Создать встречу» "
         "и «Создать собрание»."),
        ("views", "Вид календаря", "День, рабочая неделя, неделя или месяц. Кнопка «Сегодня» возвращает к текущему дню.", None,
         "Выберите удобный вид: день, рабочая неделя, неделя или месяц. Кнопка «Сегодня» возвращает к текущей дате."),
        ("grid", "Ваше расписание", "Двойной щелчок по свободному месту — новая встреча. Событие можно перетащить мышью на другое время.", None,
         "В центре — ваше расписание. Двойной щелчок по свободному месту создаёт новую встречу. Событие можно перетащить мышью на другое время."),
        ("mini", "Месяц и календари", "Щёлкните дату в маленьком календаре, чтобы перейти к ней. Ниже — ваш календарь и общие календари.", None,
         "Слева — календарь на месяц для быстрого перехода к нужной дате. Под ним — список календарей: ваш и общие."),
    ]
    for i, (zn, dt, db, tip, nt) in enumerate(data):
        s, z = tour(k, "m4-win-%d" % (i + 1), T, mock.calendar_window, zn, "Что где находится", CAL, i, dt, db, tip=tip, notes=nt,
                    side_name="cal", glow="c")

    # ------------------------------------------------------------------ appointment vs meeting
    s = k.slide("m4-types", title="Встреча или собрание?", sub="В Outlook это два разных события — не перепутайте кнопки", glow="d",
                notes="В Outlook есть два типа событий. Встреча — это событие только в вашем календаре, никому ничего не отправляется. "
                      "Собрание — это встреча с участниками: Outlook рассылает приглашения и собирает ответы.")
    cw = (CW - 1.2) / 2
    for side, (icn, ttl, tag, body, ex) in enumerate((
            ("calendar-plus", "Встреча", "ТОЛЬКО ДЛЯ ВАС", "Событие в вашем календаре. Никому ничего не отправляется.",
             ["Подготовить отчёт", "Визит к клиенту", "Обед"]),
            ("users", "Собрание", "С УЧАСТНИКАМИ", "Outlook рассылает приглашения коллегам и собирает их ответы.",
             ["Планёрка", "Совещание", "Обучение"]))):
        cx = MX + side * (cw + 1.2)
        s.begin("type%d" % side)
        s.rrect(cx, 2.2, cw, 3.55, r=0.28, fill="glass", line="glass")
        s.pic(ic(icn), cx + 0.35, 2.5, w=0.52)
        s.text(cx + 1.05, 2.46, cw - 1.4, 0.26, tag, sz=11, color=A("ACC_SOFT"), font=FONT_SB, anchor="ctr")
        s.text(cx + 1.05, 2.7, cw - 1.4, 0.4, ttl, sz=22, color=WHITE, font=FONT_SB, anchor="ctr")
        s.line(cx + 0.35, 3.3, cx + cw - 0.35, 3.3, color=(WHITE, 20))
        s.text(cx + 0.35, 3.46, cw - 0.7, 0.75, body, sz=14.5, color=TEXT, lnsp=1.0)
        s.text(cx + 0.35, 4.3, cw - 0.7, 0.28, "Например", sz=11.5, color=MUTED)
        px = cx + 0.35
        for e_ in ex:
            px += pill(s, px, 4.66, e_, sz=12, h=0.4, fill=(WHITE, 6), line="glass2", color=WHITE, pad=0.18) + 0.1
        s.end(anim=150 + side * 200)
    s.oval(SW / 2 - 0.42, 3.55, 0.84, 0.84, fill=("grad", [(0, A("CARD1"), None), (100, "0A0A10", None)], 60), line=A("ACC"), lw=1.5,
           text="или", sz=14, color=WHITE, font=FONT_SB, align="ctr", anchor="ctr", inset=(0, 0, 0, 0.02), name="types-vs", anim=300)
    note(s, MX, 6.0, CW, "Отпуск, командировка, день рождения коллеги — отметьте галочку **«Целый день»**: событие займёт весь день и не привязано к часам.",
         icon="calendar-range", anim=650)

    # ------------------------------------------------------------------ a meeting step by step (morph tour)
    T = "Новое собрание: шаг за шагом"
    sx = MX + mock.MEET_W * 0.925 + 0.48
    sw = SW - MX - sx
    HT = mock.MEET_H * 0.925 + 0.04
    data = [
        ("title", 1, "Название", "Коротко о сути: «Итоги октября: обсуждение отчёта». По названию коллега сразу поймёт, зачем его зовут. В старых версиях поле называется «Тема».", "Ctrl+Shift+Q",
         "Нажмите «Создать собрание». Сначала заполните название: коротко о сути встречи. По названию коллега сразу поймёт, зачем его зовут."),
        ("people", 2, "Участники", "«Обязательный» — те, без кого встреча не имеет смысла. «Необязательный» — кому полезно, но не обязательно. В старых версиях оба поля заменяет кнопка «Кому».", None,
         "Добавьте участников. В поле «Обязательный» — тех, без кого встреча не имеет смысла. В поле «Необязательный» — тех, "
         "кому она полезна, но присутствие не обязательно."),
        ("time", 3, "Время", "Дата, начало и окончание. Не занимайте час, если хватит тридцати минут.", None,
         "Укажите дату, время начала и окончания. Не занимайте у коллег целый час, если достаточно тридцати минут."),
        ("place", 4, "Место", "Напишите, где встречаетесь, или выберите переговорную кнопкой «Поиск помещений».", None,
         "Укажите место: напишите его вручную или выберите переговорную через «Поиск помещений»."),
        ("body", 5, "Повестка", "Цель и вопросы для обсуждения. Участники придут подготовленными, и встреча пройдёт быстрее.", None,
         "В тексте приглашения напишите цель встречи и вопросы для обсуждения. Тогда участники придут подготовленными."),
        ("send", 6, "Отправить", "Приглашения уйдут всем участникам, а собрание появится в календарях — вашем и коллег.", None,
         "Нажмите «Отправить». Приглашения уйдут всем участникам, а собрание появится в календарях."),
    ]
    for i, (zn, fill, dt, db, tip, nt) in enumerate(data):
        s = k.slide("m4-meet-%d" % (i + 1), title=T, glow="a", dur=900, notes=nt)
        z = mock.meeting_window(s, MX, 1.78, k=0.925, fill=fill)
        mock.highlight(s, z[zn])
        side_stepper(s, sx, 1.76, sw, STEPS, i, dt, db, tip=tip, name="meet", h_total=HT)

    # ------------------------------------------------------------------ scheduling assistant (two states, morph)
    for j, (slot, good) in enumerate(((1, False), (4, True))):
        s = k.slide("m4-assist-%d" % (j + 1), title="Помощник по планированию: когда все свободны",
                    sub="Вкладка в окне собрания: показывает занятость каждого участника", glow="b", dur=900, title_w=10.8,
                    notes="Чтобы не выяснять в переписке, когда кому удобно, откройте в окне собрания «Помощник по планированию». "
                          "Каждая строка — участник, цветные блоки — время, когда он занят." if not good else
                          "Найдите столбец, где нет ни одного блока, и щёлкните по нему — время собрания изменится. "
                          "Здесь все свободны с одиннадцати до двенадцати.")
        gx, gy, gw, gh = MX, 2.25, 7.9, 4.2
        zone = mock.assistant_grid(s, gx, gy, gw, gh, slot=slot, show_slot=False)
        col = OK if good else BAD
        s.rrect(zone[0], zone[1], zone[2], zone[3], r=0.06, fill=(col, 16), line=col, lw=1.75, name="!!assist-slot")
        px = gx + gw + 0.45
        pw = SW - MX - px
        s.rrect(px, gy, pw, gh, r=0.26, fill="glass", line="glass", name="!!assist-card")
        s.pic("ic_circle-check_ok.png" if good else "ic_circle-x_bad.png", px + 0.32, gy + 0.32, w=0.5, name="assist-ic")
        s.text(px + 0.95, gy + 0.3, pw - 1.2, 0.54, "11:00 — все свободны" if good else "9:30 — заняты трое", sz=16, color=col, font=FONT_SB,
               anchor="ctr", name="assist-t")
        s.line(px + 0.32, gy + 1.02, px + pw - 0.32, gy + 1.02, color=(WHITE, 20), name="!!assist-ln")
        if good:
            body = [{"t": "Столбец без единого блока — это время, удобное всем.", "spcAft": 8},
                    {"t": "Щёлкните по нему: дата и время собрания подставятся сами.", "spcAft": 8},
                    {"t": "Переговорную тоже можно добавить в список — и сразу увидеть, свободна ли она.", "color": MUTED}]
        else:
            body = [{"t": "Строка — участник. Цветной блок — он занят.", "spcAft": 8},
                    {"t": "Чем именно занят коллега, вы не видите — только время.", "spcAft": 8},
                    {"t": "В 9:30 заняты трое: приглашение, скорее всего, отклонят.", "color": MUTED}]
        s.text(px + 0.32, gy + 1.2, pw - 0.64, gh - 1.4, body, sz=14, color=TEXT, lnsp=1.02, name="assist-b")

    # ------------------------------------------------------------------ replying to an invitation
    s = k.slide("m4-answer", title="Вам пришло приглашение", sub="В письме-приглашении есть четыре кнопки — выберите одну", glow="c",
                notes="Когда вам приходит приглашение, в письме есть четыре кнопки. «Принять» — собрание появится в календаре. «Под вопросом» — "
                      "если вы не уверены. «Отклонить» — если не сможете прийти. «Предложить новое время» — если время не подходит. "
                      "Отвечайте на каждое приглашение: организатор видит, кто придёт.")
    items = [
        dict(img="ic_circle-check_ok.png", title="Принять", body="Собрание появится в вашем календаре, организатор получит ответ."),
        dict(img="ic_circle-help_warn.png", title="Под вопросом", body="Не уверены, что сможете. Время в календаре займётся предварительно."),
        dict(img="ic_circle-x_bad.png", title="Отклонить", body="Не сможете прийти. Хороший тон — коротко объяснить причину."),
        dict(img=ic("calendar-clock"), title="Предложить новое время", body="Время не подходит — предложите своё. Решение примет организатор."),
    ]
    h, used, gy = grid(s, items, y=2.25, cols=4, gap=0.26, img_h=0.5, after=1.0)
    note(s, MX, gy + used + 0.3, CW, "Отвечайте на **каждое** приглашение. Организатор видит ответы всех участников и понимает, состоится ли встреча.",
         icon="message-square-reply", anim=650)

    # ------------------------------------------------------------------ recurrence, reminder, changes
    s = k.slide("m4-more", title="Повторение, напоминание, перенос и отмена", sub="Четыре возможности, которые пригодятся организатору", glow="d", title_w=10.6,
                notes="Ещё четыре возможности. Повторение — для регулярных встреч, например еженедельной планёрки. Напоминание — по умолчанию "
                      "за пятнадцать минут. Чтобы перенести собрание, измените время и нажмите «Отправить обновление». Чтобы отменить — "
                      "«Отменить собрание» и «Отправить отмену».")
    items = [
        dict(icon="repeat", title="Повторение", body="Планёрка каждый понедельник? Кнопка «Повторение» создаст её сразу на все недели."),
        dict(icon="bell", title="Напоминание", body="Обычно за 15 минут. Встреча в другом здании — поставьте за 30 или 60."),
        dict(icon="calendar-clock", title="Перенос", body="Откройте собрание, измените время и нажмите «Отправить обновление»."),
        dict(icon="calendar-x", title="Отмена", body="«Отменить собрание» → «Отправить отмену». Тогда оно исчезнет из календарей у всех."),
    ]
    grid(s, items, y=2.25, cols=4, gap=0.26)

    # ------------------------------------------------------------------ your calendar is visible to colleagues
    s = k.slide("m4-share", title="Ваш календарь видят коллеги", sub="Поэтому держите его в актуальном состоянии", glow="a",
                notes="Коллеги видят в вашем календаре, когда вы заняты, — обычно без подробностей. Поэтому вносите в календарь отпуск "
                      "и командировки, личные события помечайте как частные, а календарь коллеги можно открыть кнопкой «Открыть календарь».")
    items = [
        dict(icon="eye", title="Видно только занятость", body="Обычно коллеги видят, что вы заняты, но не видят тему и подробности встречи."),
        dict(icon="plane-takeoff", title="Отпуск и командировка", body="Внесите в календарь и выберите «Показать как» → «Нет на месте»."),
        dict(icon="lock", title="Личное в рабочее время", body="Отметьте событие кнопкой «Частное» — подробности не увидит никто."),
        dict(icon="users", title="Календарь коллеги", body="«Открыть календарь» → «Из адресной книги» — и его расписание рядом с вашим."),
    ]
    grid(s, items, y=2.25, cols=2, gap=0.28, inline=True)

    # ------------------------------------------------------------------ check yourself
    quiz(k, "m4-q1", "Как быстрее всего найти время, удобное всем?",
         ["Написать каждому письмо и спросить, когда он свободен", "Создать собрание и открыть «Помощник по планированию»", "Назначить на завтра на 9:00 — подстроятся"], 1,
         "«Помощник по планированию» показывает занятость всех участников сразу. Свободное время видно за несколько секунд — без переписки.",
         situation="Вам нужно обсудить отчёт с тремя коллегами.",
         tag="Проверьте себя · вопрос 1 из 2")
    quiz(k, "m4-q2", "Вы организатор, и собрание нужно отменить. Что сделать?",
         ["Просто удалить его из своего календаря", "Открыть собрание → «Отменить собрание» → «Отправить отмену»", "Ничего: участники сами поймут, когда никто не придёт"], 1,
         "После «Отправить отмену» все участники получат уведомление, и собрание исчезнет из их календарей.",
         tag="Проверьте себя · вопрос 2 из 2")
