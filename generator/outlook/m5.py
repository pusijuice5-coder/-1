# -*- coding: utf-8 -*-
"""Module 5. Security and etiquette: phishing signs, what to do, mailbox rules, tone."""
from kit import *
import mock


def build(k):
    k.mod = 4
    opener(k, "m5-open", "05", "Безопасность и этикет",
           "Одно неосторожное нажатие может стоить банку и клиентам очень дорого.",
           ["Как распознать опасное письмо", "Что делать, если письмо вызывает сомнения",
            "Пять правил рабочей почты", "Как писать вежливо и по делу"],
           "o_lock.png", "≈ 5 минут",
           notes="Модуль пятый. Безопасность и этикет. Через почту приходит большинство атак на банки. Вы научитесь распознавать опасные "
                 "письма и узнаете главные правила рабочей переписки.")

    # ------------------------------------------------------------------ phishing: five signs
    s = k.slide("m5-phish", title="Пять признаков опасного письма", sub="Мошенники маскируют письма под службу поддержки, руководителя или банк-партнёр",
                glow="b", title_w=10.8,
                notes="Посмотрите на это письмо. В нём пять признаков опасности. Первый: странный адрес отправителя. Второй: срочность и угрозы. "
                      "Третий: просят ввести пароль. Четвёртый: ссылка ведёт на незнакомый сайт. Пятый: неожиданное вложение.")
    lx, ly, lw, lh = MX, 2.25, 6.35, 4.25
    pts = letter(s, lx, ly, lw, lh, "Служба поддержки", "it-support@bank-helpdesk.info",
                 "СРОЧНО! Ваша учётная запись будет заблокирована",
                 ["Уважаемый пользователь!", "Срок действия вашего пароля истекает сегодня. Чтобы сохранить доступ, перейдите по ссылке и введите логин и пароль:",
                  "~~http://bank-login.portal-check.info~~", "Через 2 часа учётная запись будет удалена."],
                 attach="Инструкция.zip", name="phish-letter", anim=100, danger=True, sz=12.5, rpad=0.85)
    bx = lx + lw - 0.52
    marks = [(pts["from"][0], pts["from"][1] - 0.03), (bx, ly + 1.12), (bx, pts["p1y"][0] + 0.1), (bx, pts["p2y"][0] - 0.06), (pts["attach"][0], pts["attach"][1] + 0.03)]
    for i, (mx_, my_) in enumerate(marks):
        num_badge(s, mx_, my_, i + 1, d=0.32, name="ph-b%d" % i, anim=350 + i * 100, color=BAD)
    num_list(s, lx + lw + 0.5, 2.3, CW - lw - 0.5,
             [("Странный адрес отправителя", "Похож на настоящий, но домен другой."),
              ("Срочность и угрозы", "«Немедленно», «заблокируем», «последнее предупреждение»."),
              ("Просят пароль или код", "Настоящая поддержка никогда их не спрашивает."),
              ("Ссылка на незнакомый сайт", "Наведите курсор — увидите, куда она ведёт на самом деле."),
              ("Неожиданное вложение", "Особенно архивы и файлы с непонятным расширением.")], sz=13.5, gap=0.19, anim0=350)

    # ------------------------------------------------------------------ what to do
    s = k.slide("m5-do", title="Письмо вызывает сомнения? Три шага", sub="Сомневаетесь — значит, не нажимайте", glow="c",
                notes="Если письмо вызывает сомнения, сделайте три шага. Не нажимайте: не открывайте ссылки и вложения, не отвечайте. "
                      "Сообщите в службу информационной безопасности. И проверьте другим способом: если письмо как будто от коллеги — "
                      "позвоните ему. А если вы уже нажали на ссылку или ввели пароль — сразу сообщите, не скрывайте.")
    used = process(s, 2.25, [
        ("Не нажимайте", "Не открывайте ссылки и вложения. Не отвечайте на письмо."),
        ("Сообщите", "В службу информационной безопасности — так, как принято в банке."),
        ("Проверьте иначе", "Письмо «от коллеги»? Позвоните ему по известному вам номеру."),
    ])
    note(s, MX, 2.25 + used + 0.3, CW, "**Уже нажали или ввели пароль?** Не скрывайте — сразу сообщите в службу ИБ. Чем раньше о проблеме узнают, тем меньше ущерб.",
         icon="siren", anim=700)

    # ------------------------------------------------------------------ five rules
    s = k.slide("m5-rules", title="Рабочая почта: пять правил", sub="Они защищают и банк, и клиентов, и вас", glow="d",
                notes="Пять правил рабочей почты. Используйте её только для работы. Не пересылайте рабочие письма на личную почту. "
                      "Проверяйте адресатов перед отправкой. Данные клиентов отправляйте только по правилам банка. "
                      "И блокируйте компьютер, когда отходите: клавиши Виндоус и Эл.")
    rows(s, MX, 2.2, CW,
         [("briefcase", "Только для работы", "Не регистрируйтесь с рабочим адресом на посторонних сайтах и в соцсетях."),
          ("ban", "Не на личную почту", "Рабочие письма и документы не пересылаются на личные адреса."),
          ("users", "Проверяйте адресатов", "Автоподстановка может выбрать однофамильца или внешний адрес."),
          ("file-lock", "Данные клиентов — по правилам", "Персональные данные и банковскую тайну отправляйте только так, как разрешено в банке."),
          ("lock-keyhole", "Блокируйте компьютер", "Отходите от рабочего места — нажмите Win + L.")], rh=0.7, tw=3.35, bsz=13.5)

    # ------------------------------------------------------------------ etiquette
    s = k.slide("m5-etiq", title="Этикет: письмо, которое приятно получить", sub="По письмам судят и о вас, и о банке", glow="a", title_w=10.4,
                notes="Несколько слов об этикете. Здоровайтесь и обращайтесь по имени. Отвечайте в течение рабочего дня — хотя бы коротко: "
                      "«Получил, отвечу до среды». Одна тема — одно письмо. Не пишите заглавными буквами, не ставьте высокую важность "
                      "на каждое письмо, а спорные вопросы лучше обсудить по телефону.")
    compare(s, 2.2,
            ["ПИСАТЬ ЗАГЛАВНЫМИ и ставить «!!!»", "«Высокая важность» на каждом письме", "«Ответить всем», когда ответ нужен одному", "Выяснять отношения в переписке"],
            ["Поздороваться и обратиться по имени", "Ответить в течение рабочего дня — хотя бы «Получил, отвечу до среды»", "Одна тема — одно письмо", "Спорный вопрос обсудить по телефону"],
            sz=14)

    # ------------------------------------------------------------------ check yourself
    quiz(k, "m5-q1", "Что вы сделаете?",
         ["Перейду по ссылке и введу пароль — вдруг и правда заблокируют", "Отвечу на письмо и спрошу, настоящее ли оно",
          "Не буду нажимать и сообщу в службу информационной безопасности"], 2,
         "Срочность, незнакомый адрес и просьба ввести пароль — признаки фишинга. Не нажимайте и сообщите в службу ИБ. Отвечать мошенникам тоже не стоит.",
         situation="Пришло письмо «от службы поддержки»: пароль истекает, нужно срочно перейти по ссылке и ввести логин и пароль. Адрес отправителя вам незнаком.",
         tag="Проверьте себя · вопрос 1 из 2")
    quiz(k, "m5-q2", "Можно ли переслать рабочие документы на личную почту?",
         ["Да, если потом удалить письмо", "Нет: рабочие документы не должны покидать почту банка", "Да, если в документе нет персональных данных"], 1,
         "Личная почта банком не защищена. Если нужно работать вне офиса — обратитесь к руководителю: для этого есть разрешённые способы.",
         situation="Вы не успели доделать отчёт и хотите закончить его дома.",
         tag="Проверьте себя · вопрос 2 из 2")
