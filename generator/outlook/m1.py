# -*- coding: utf-8 -*-
"""Module 1. Getting to know Outlook: what it is, the window, folders, message marks."""
from kit import *
import mock

ZONES = ["Лента", "Панель папок", "Список писем", "Область чтения", "Переключатель разделов"]
ZKEYS = ["ribbon", "folders", "list", "reading", "nav"]


def build(k):
    k.mod = 0
    opener(k, "m1-open", "01", "Знакомство с Outlook",
           "Разберёмся, как устроено окно программы, — и дальше всё станет проще.",
           ["Из каких областей состоит окно Outlook", "Какие папки есть в почте и зачем каждая", "Что означают значки рядом с письмами"],
           "t_band.jpg", "≈ 6 минут", tile=True,
           notes="Модуль первый. Знакомство с Outlook. Вы узнаете, из каких областей состоит окно программы, какие папки есть в почте "
                 "и что означают значки рядом с письмами.")

    # ------------------------------------------------------------------ one program - four tools
    s = k.slide("m1-what", title="Outlook — это четыре инструмента в одном окне", sub="Почта — главный из них, но рядом всегда календарь, контакты и задачи",
                title_w=10.6,
                notes="Outlook — это не только почта. В одном окне собраны четыре инструмента: почта, календарь, контакты и задачи. "
                      "В этом курсе мы подробно разберём первые два — почту и календарь.")
    items = [
        dict(img=obj("i_envelope"), title="Почта", body="Письма, вложения и вся рабочая переписка.", tag="В ЭТОМ КУРСЕ"),
        dict(img=obj("i_calendar"), title="Календарь", body="Встречи, собрания и напоминания о них.", tag="В ЭТОМ КУРСЕ"),
        dict(img=obj("i_people"), title="Люди", body="Адресная книга банка и ваши контакты.", tag="КОРОТКО"),
        dict(img=obj("i_check"), title="Задачи", body="Список дел и письма с флажком «К исполнению».", tag="КОРОТКО"),
    ]
    h, used, gy = grid(s, items, y=2.25, cols=4, gap=0.26, img_h=1.0, after=1.0)
    note(s, MX, gy + used + 0.3, CW, "Переключаться между ними можно значками в левом нижнем углу окна или клавишами **Ctrl+1** (почта) и **Ctrl+2** (календарь).",
         icon="keyboard", anim=650)

    # ------------------------------------------------------------------ window tour (morph)
    descr = [
        ("Лента", "Все команды программы. Вкладка «Главная» — самое нужное: создать письмо, ответить, переслать, удалить.",
         "Лента — это панель с командами в верхней части окна. На вкладке «Главная» собрано самое нужное: создать сообщение, "
         "ответить, переслать, удалить."),
        ("Панель папок", "Слева — ваши папки: «Входящие», «Отправленные», «Черновики» и другие. Цифра рядом — число непрочитанных писем.",
         "Слева находится панель папок. Жирная цифра рядом с папкой показывает, сколько в ней непрочитанных писем."),
        ("Список писем", "Письма выбранной папки: от кого, тема, начало текста и время. Непрочитанные выделены жирным. Сверху — строка поиска.",
         "В центре — список писем выбранной папки. Непрочитанные выделены жирным шрифтом. Над списком находится строка поиска."),
        ("Область чтения", "Справа открывается выбранное письмо — его можно прочитать, не открывая в отдельном окне. Вложения видны тут же.",
         "Справа — область чтения. Щёлкните письмо в списке, и его текст появится здесь. Вложения тоже видны сразу."),
        ("Переключатель разделов", "Значки внизу слева переключают Outlook между почтой, календарём, контактами и задачами.",
         "В левом нижнем углу — значки разделов: почта, календарь, люди и задачи."),
    ]
    s = k.slide("m1-win-0", title="Окно Outlook: пять областей", glow="c", dur=900,
                notes="Посмотрим на главное окно Outlook. В нём пять областей: лента с командами, панель папок, список писем, область чтения "
                      "и переключатель разделов. Пройдём по каждой.")
    z = mock.mail_window(s, MX, 1.78, k=0.925, badges=ZKEYS)
    wx, wy, ww, wh = z["win"]
    sx = wx + ww + 0.48
    side_steps(s, sx, 1.76, SW - MX - sx, "Области окна", ZONES, -1, "Всё на своих местах",
               "Окно выглядит одинаково каждый день. Запомните пять областей — и вы всегда будете знать, где что искать.",
               name="tour", h_total=wh + 0.04)
    for i, (zt, zb, zn) in enumerate(descr):
        s = k.slide("m1-win-%d" % (i + 1), title="Окно Outlook: пять областей", glow="c", dur=900, notes=zn)
        z = mock.mail_window(s, MX, 1.78, k=0.925, badges=ZKEYS, active_badge=ZKEYS[i])
        mock.highlight(s, z[ZKEYS[i]])
        side_steps(s, sx, 1.76, SW - MX - sx, "Области окна", ZONES, i, zt, zb, name="tour", h_total=wh + 0.04)

    # ------------------------------------------------------------------ folders
    s = k.slide("m1-folders", title="Папки: что где лежит", sub="Эти папки есть у каждого — Outlook создаёт их сам", glow="d",
                notes="В почте есть несколько стандартных папок. Входящие — сюда приходят новые письма. Черновики — письма, которые вы начали "
                      "и не отправили. Отправленные — копии отправленных писем. Удалённые — корзина. Нежелательная почта — спам, "
                      "а Архив — письма, которые уже не нужны под рукой.")
    items = [
        dict(icon="inbox", title="Входящие", body="Сюда приходят все новые письма."),
        dict(icon="pen-line", title="Черновики", body="Письма, которые вы начали и не отправили. Outlook сохраняет их сам."),
        dict(icon="send", title="Отправленные", body="Копии всех писем, которые вы отправили."),
        dict(icon="trash-2", title="Удаленные", body="Корзина. Письмо можно вернуть, пока папку не очистили."),
        dict(icon="ban", title="Нежелательная почта", body="Спам. Иногда сюда по ошибке попадают нужные письма — заглядывайте."),
        dict(icon="archive", title="Архив", body="Письма, которые не нужны под рукой, но могут пригодиться."),
    ]
    grid(s, items, y=2.25, cols=3, gap=0.26, pad=0.3, inline=True)

    # ------------------------------------------------------------------ marks in the message list
    s = k.slide("m1-marks", title="Значки в списке писем", sub="По ним видно состояние письма — даже не открывая его", glow="a",
                notes="Рядом с письмами в списке есть значки. Жирный шрифт и цветная полоса — письмо не прочитано. Скрепка — есть вложение. "
                      "Восклицательный знак — отправитель отметил письмо как важное. Флажок — вы пометили письмо к исполнению. "
                      "Стрелки показывают, что вы ответили на письмо или переслали его.")
    items = [
        dict(icon="mail", title="Жирный шрифт и цветная полоса", body="Письмо не прочитано."),
        dict(icon="paperclip", title="Скрепка", body="В письме есть вложение."),
        dict(icon="circle-alert", title="Восклицательный знак", body="Отправитель отметил: «Высокая важность»."),
        dict(icon="flag", title="Флажок", body="Письмо отмечено «К исполнению» — к нему нужно вернуться."),
        dict(icon="reply", title="Стрелка влево", body="Вы ответили на это письмо."),
        dict(icon="forward", title="Стрелка вправо", body="Вы переслали это письмо."),
    ]
    grid(s, items, y=2.25, cols=3, gap=0.26, pad=0.3, inline=True)

    # ------------------------------------------------------------------ check yourself
    quiz(k, "m1-q1", "Вы начали писать письмо, но отвлеклись и закрыли окно. Где искать недописанное письмо?",
         ["В папке «Входящие»", "В папке «Черновики»", "В папке «Отправленные»", "В папке «Удаленные»"], 1,
         "Outlook сам сохраняет недописанные письма в папке «Черновики». Откройте письмо оттуда и продолжайте.",
         tag="Проверьте себя · вопрос 1 из 2")
    quiz(k, "m1-q2", "Рядом с папкой «Входящие» стоит цифра 3. Что она означает?",
         ["В папке три письма с вложениями", "В папке три непрочитанных письма", "Сегодня пришло три письма"], 1,
         "Цифра рядом с папкой — это число непрочитанных писем. Прочитаете их — цифра исчезнет.",
         tag="Проверьте себя · вопрос 2 из 2")
