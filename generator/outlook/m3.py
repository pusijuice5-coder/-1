    s.rrect(LX, 2.2, 5.6, 0.52, r=0.26, fill="16141C", line="glass")
    s.pic(ic("search"), LX + 0.2, 2.33, w=0.26)
    s.text(LX + 0.6, 2.2, 3.5, 0.52, "отчёт октябрь", sz=15, color=WHITE, anchor="ctr")
    s.rect(LX + 0.6 + text_width("отчёт октябрь", 15) + 0.05, 2.33, 0.015, 0.26, fill=A("ACC"))
    s.end(anim=100)
    kx = LX + 5.85
    s.begin("search-keys")
    keys(s, kx, 2.24, "Ctrl+E")
