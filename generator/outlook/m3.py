    s.text(IX + 0.45, cy + 0.38, 1.7, 0.3, "Договор № 45", sz=11.5, color=TEXT, anchor="ctr")
    s.rrect(IX + IW - 1.72, cy + 0.44, 0.62, 0.2, r=0.05, fill="8A6BFF")
