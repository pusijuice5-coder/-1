TOOLS = ["Поиск", "Папки", "Категории", "Флажки", "Правила", "Автоответ"]
LX, LW = MX, 8.2          # left content area
NX = MX + LW + 0.5        # menu on the right
NW = SW - MX - NX
IX, IW = MX + 4.6, 3.6    # illustration card inside the left area
IY, IH = 3.0, 3.45


def tool(k, key, idx, title, sub, path, tips, notes):
    s = k.slide(key, title=title, sub=sub, notes=notes, glow="abcd"[idx % 4], dur=900, title_w=8.6)
    side_steps(s, NX, 2.2, NW, "Инструменты", TOOLS, idx, name="tools")
    if path:
        path_steps(s, LX, 2.22, path, sz=13, h=0.46, name="tool-path", anim=100)
    num_list(s, LX, IY + 0.08, 4.25, tips, sz=13.5, gap=0.22, anim0=220)
    s.rrect(IX, IY, IW, IH, r=0.26, fill="glass", line="glass", name="!!tool-ill")
    return s


def build(k):
    k.mod = 2
    opener(k, "m3-open", "03", "Порядок в почте",
           "Чтобы нужное письмо находилось за секунды, а важное не терялось.",
           ["Что делать с каждым входящим письмом", "Как найти письмо и разложить почту по папкам",
            "Как Outlook может сортировать письма сам", "Как включить автоответ на время отпуска"],
           obj("i_folder"), "≈ 7 минут",
           notes="Модуль третий. Порядок в почте. Вы узнаете, что делать с каждым входящим письмом, как быстро находить нужное, "
                 "как настроить автоматическую сортировку и автоответ.")

    # ------------------------------------------------------------------ four actions (process)
    s = k.slide("m3-four", title="Что делать с каждым письмом: четыре действия", sub="Открыли письмо — сразу решите его судьбу", glow="b", title_w=10.8,
                notes="Главное правило порядка: открыв письмо, сразу решите, что с ним делать. Не нужно — удалите. Ответ займёт пару минут — "
                      "ответьте сразу. Вопрос не ваш — перешлите тому, кто его решает. Нужно время — поставьте флажок или запланируйте "
                      "в календаре.")
    used, py = process(s, 2.25, [
        ("Удалить", "Письмо не нужно — сразу в корзину. Не копите."),
        ("Сделать", "Ответ займёт пару минут — ответьте сейчас."),
        ("Передать", "Вопрос не ваш — перешлите тому, кто его решает."),
        ("Отложить", "Нужно время — поставьте флажок или запланируйте в календаре."),
    ])
