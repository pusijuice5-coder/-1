# -*- coding: utf-8 -*-
"""Module 2. Messages: create and send step by step, To/Cc/Bcc, subject, structure, reply/forward, attachments, signature."""
from kit import *
import mock

STEPS = ["Новое письмо", "Кому", "Копия", "Тема", "Текст", "Вложение", "Отправить"]


def build(k):
    k.mod = 1
    opener(k, "m2-open", "02", "Письма",
           "Научимся писать письма, на которые отвечают быстро и по делу.",
           ["Как создать и отправить письмо шаг за шагом", "Чем отличаются «Кому», «Копия» и «Скрытая копия»",
            "Когда отвечать всем, а когда пересылать", "Как написать письмо, которое поймут с первого раза"],
           obj("i_envelope"), "≈ 9 минут",
           notes="Модуль второй. Письма. Вы научитесь создавать и отправлять письмо, правильно заполнять поля получателей, "
                 "отвечать и пересылать, а главное — писать так, чтобы вас понимали с первого раза.")

    # ------------------------------------------------------------------ compose step by step (morph tour)
    T = "Новое письмо: шаг за шагом"
    sx = MX + mock.COMPOSE_W * 0.925 + 0.48
    sw = SW - MX - sx
    HT = mock.COMPOSE_H * 0.925 + 0.04
    # step 1: the main window, 'Create message'
    s = k.slide("m2-new-1", title=T, glow="c", dur=900,
                notes="Чтобы написать письмо, на вкладке «Главная» нажмите кнопку «Создать сообщение». Или нажмите клавиши Контрол и Эн.")
    z = mock.mail_window(s, MX, 1.78, k=0.77)
    mock.highlight(s, z["new"])
    side_stepper(s, sx, 1.76, sw, STEPS, 0, "Создайте письмо",
                 "На вкладке «Главная» нажмите «Создать сообщение». Откроется окно нового письма.", tip="Ctrl + N", name="cmp", h_total=HT)
    s.pic(ic("mouse-pointer-click", white=True), z["new"][0] + 0.42, z["new"][1] + 0.44, w=0.42, name="cmp-cur")
    data = [
        ("to", 1, "Кому", "Начните вводить имя или фамилию — Outlook подскажет адрес из адресной книги банка. Сюда — тех, от кого ждёте ответа или действия.", None,
         "В поле «Кому» укажите получателей. Начните вводить фамилию — Outlook сам предложит адрес из адресной книги банка."),
        ("cc", 2, "Копия", "Те, кому письмо нужно для сведения. Отвечать на него они не обязаны.", None,
         "В поле «Копия» добавьте тех, кому письмо нужно для сведения."),
        ("subject", 3, "Тема", "Одна строка о сути письма. По теме решают, открыть ли письмо сейчас, — и по ней же его потом ищут.", None,
         "Обязательно заполните тему. Это одна строка о сути письма: по ней получатель решает, когда открыть письмо, и по ней же потом его ищет."),
        ("text", 4, "Текст", "Приветствие, суть, что нужно от получателя и к какому сроку. Подпись подставится сама, если она настроена.", None,
         "Напишите текст: приветствие, суть, что вы просите и к какому сроку. Подпись подставится автоматически, если вы её настроили."),
        ("attach_btn", 5, "Вложение", "Нажмите «Вложить файл» и выберите документ. Можно просто перетащить файл мышью в окно письма.", None,
         "Чтобы прикрепить документ, нажмите «Вложить файл». Или просто перетащите файл мышью в окно письма."),
        ("send", 6, "Отправить", "Проверьте адресатов, тему и вложение — и нажмите «Отправить». Копия письма появится в папке «Отправленные».", "Ctrl + Enter",
         "Проверьте адресатов, тему и вложение и нажмите «Отправить». Копия письма сохранится в папке «Отправленные»."),
    ]
    for i, (zn, fill, dt, db, tip, nt) in enumerate(data):
        s = k.slide("m2-new-%d" % (i + 2), title=T, glow="c", dur=900, notes=nt)
        z = mock.compose_window(s, MX, 1.78, k=0.925, fill=fill)
        mock.highlight(s, z[zn])
        side_stepper(s, sx, 1.76, sw, STEPS, i + 1, dt, db, tip=tip, name="cmp", h_total=HT)

    # ------------------------------------------------------------------ To / Cc / Bcc
    s = k.slide("m2-to", title="Кому, Копия и Скрытая копия", sub="Три поля — три разные роли получателя", glow="d",
                notes="В чём разница между полями. «Кому» — основные получатели, от них вы ждёте ответа или действия. «Копия» — те, кому письмо "
                      "нужно для сведения. «Скрытая копия» — получатель, которого не видят остальные; она подходит для рассылки большому "
                      "списку, чтобы не раскрывать адреса.")
    items = [
        dict(icon="user-check", tag="ЖДЁТЕ ОТВЕТА", title="Кому", body="Основные получатели. От них вы ждёте ответа или действия."),
        dict(icon="eye", tag="ДЛЯ СВЕДЕНИЯ", title="Копия", body="Должны быть в курсе, но отвечать не обязаны. Всем видно, кто стоит в копии."),
        dict(icon="eye-off", tag="НЕ ВИДНО ДРУГИМ", title="Скрытая копия (СК)", body="Получатель скрыт от остальных. Удобно для рассылки большому списку — адреса не раскрываются."),
    ]
    h, used = grid(s, items, y=2.2, cols=3, gap=0.28)
    note(s, MX, 2.2 + used + 0.28, CW, "Не видите поле «СК»? В окне письма откройте вкладку **«Параметры»** и нажмите **«СК»**.", icon="lightbulb", anim=560)

    # ------------------------------------------------------------------ subject
    s = k.slide("m2-subject", title="Тема письма: одна строка решает всё", sub="Формула хорошей темы: что это + что нужно + срок", glow="a",
                notes="Тема — первое, что видит получатель. Плохие темы: «Вопрос», «Срочно» или вообще пустая строка. Хорошая тема отвечает "
                      "на три вопроса: что это, что нужно сделать и к какому сроку. Например: «Договор номер сорок пять: прошу согласовать "
                      "до тринадцатого ноября».")
    compare(s, 2.2, ["Вопрос", "СРОЧНО!!!", "Документы", "(без темы)"],
            ["Договор № 45: прошу согласовать до 13.11", "Отчёт за октябрь — на проверку", "Заявка на отпуск: 1–14 декабря", "Планёрка 12.11: повестка и материалы"])

    # ------------------------------------------------------------------ structure of a good message
    s = k.slide("m2-struct", title="Из чего состоит хорошее письмо", sub="Пять частей — и получателю не придётся переспрашивать", glow="b",
                notes="Хорошее письмо состоит из пяти частей. Приветствие. Суть — в первом же предложении. Детали — коротко, лучше списком. "
                      "Что вы просите и к какому сроку. И подпись — чтобы было понятно, кто вы и как с вами связаться.")
    lx, ly, lw, lh = MX, 2.18, 6.5, 4.3
    pts = letter(s, lx, ly, lw, lh, "Нигора Алиева", "Кому: Азиз Каримов", "Отчёт за октябрь — прошу согласовать до 13.11",
                 ["Азиз, добрый день!", "Направляю отчёт по продажам за октябрь — прошу согласовать.",
                  "Что изменилось: добавлен раздел по филиалам и обновлены данные за третью неделю.",
                  "**Прошу прислать замечания до пятницы, 13 ноября.**",
                  "С уважением, Нигора Алиева\nГлавный специалист · Отдел продаж · вн. 1234"],
                 attach="Отчёт_октябрь_2026.xlsx", name="struct-letter", anim=100, sz=12.5, rpad=0.85)
    for i in range(5):
        num_badge(s, lx + lw - 0.52, pts["p%dy" % i][0] + min(pts["p%dy" % i][1] / 2 - 0.16, 0.12), i + 1, d=0.32, name="struct-b%d" % i, anim=350 + i * 90)
    num_list(s, lx + lw + 0.5, 2.26, CW - lw - 0.5,
             [("Приветствие", "Обратитесь по имени — письмо сразу звучит по-человечески."),
              ("Суть — в первой строке", "Зачем вы пишете. Не заставляйте искать главное."),
              ("Детали", "Коротко. Если пунктов несколько — списком."),
              ("Просьба и срок", "Что нужно сделать и к какому числу."),
              ("Подпись", "Имя, должность, подразделение, телефон.")], sz=13.5, gap=0.2, anim0=350)

    # ------------------------------------------------------------------ reply / reply all / forward
    s = k.slide("m2-reply", title="Ответить, ответить всем или переслать?", sub="Три кнопки рядом — а результат разный", glow="c",
                notes="Три кнопки стоят рядом, но работают по-разному. «Ответить» — ответ уйдёт только отправителю. «Ответить всем» — "
                      "отправителю и всем, кто был в полях «Кому» и «Копия»; используйте её, только когда ответ действительно нужен всем. "
                      "«Переслать» — письмо вместе с вложениями уйдёт новому адресату.")
    items = [
        dict(icon="reply", title="Ответить", body="Ответ получит только отправитель.", tag="CTRL + R"),
        dict(icon="reply-all", title="Ответить всем", body="Ответ получат отправитель и все, кто был в «Кому» и «Копия». Только если ответ нужен действительно всем.", tag="CTRL + SHIFT + R"),
        dict(icon="forward", title="Переслать", body="Письмо уйдёт новому адресату. Добавьте пару слов: зачем вы его пересылаете.", tag="CTRL + F"),
    ]
    h, used = grid(s, items, y=2.2, cols=3, gap=0.28)
    note(s, MX, 2.2 + used + 0.28, CW, "При **ответе** вложения исходного письма не отправляются. При **пересылке** — отправляются вместе с письмом.",
         icon="paperclip", anim=560)

    # ------------------------------------------------------------------ attachments
    s = k.slide("m2-attach", title="Вложения: три правила", sub="Чтобы файл дошёл, открылся и не потерялся", glow="d",
                notes="Три правила работы с вложениями. Первое: называйте файл понятно. Второе: упоминайте вложение в тексте письма. "
                      "Третье: большие файлы отправляйте ссылкой на общую папку — тяжёлое письмо может не дойти.")
    items = [
        dict(num="01", title="Назовите файл понятно", body="«Отчёт_октябрь_2026.xlsx», а не «Документ1.xlsx». Получатель найдёт его и через полгода."),
        dict(num="02", title="Скажите о вложении в тексте", body="«Во вложении — отчёт за октябрь». Outlook даже напомнит, если вы написали так, а файл забыли."),
        dict(num="03", title="Большой файл — ссылкой", body="Тяжёлое письмо может не дойти. Положите файл в общую папку и отправьте ссылку на него."),
    ]
    grid(s, items, y=2.2, cols=3, gap=0.28)

    # ------------------------------------------------------------------ signature
    s = k.slide("m2-sign", title="Подпись: настройте один раз", sub="И Outlook будет сам добавлять её в каждое письмо", glow="a",
                notes="Подпись настраивается один раз. Откройте меню «Файл», затем «Параметры», раздел «Почта» и нажмите «Подписи». "
                      "Создайте подпись: имя, должность, подразделение и телефон. Выберите её для новых сообщений и для ответов.")
    path_steps(s, MX, 2.25, ["Файл", "Параметры", "Почта", "Подписи…"], sz=14, h=0.5, anim=100)
    num_list(s, MX, 3.15, 5.9,
             [("Нажмите «Создать» и назовите подпись", None),
              ("Впишите текст", "Имя и фамилия, должность, подразделение, рабочий телефон."),
              ("Выберите, куда её подставлять", "Отдельно для новых сообщений и для ответов и пересылки.")], sz=14, gap=0.24, anim0=250)
    cx, cw = MX + 6.5, CW - 6.5
    s.begin("sign-card")
    s.rrect(cx, 2.25, cw, 3.3, r=0.26, fill="glass", line="glass")
    s.text(cx + 0.35, 2.5, cw - 0.7, 0.3, "ПРИМЕР ПОДПИСИ", sz=11, color=A("ACC_SOFT"), font=FONT_SB)
    s.line(cx + 0.35, 2.95, cx + cw - 0.35, 2.95, color=(WHITE, 20))
    s.text(cx + 0.35, 3.15, cw - 0.7, 2.2,
           [{"t": "С уважением,", "spcAft": 6}, {"t": "Нигора Алиева", "font": FONT_SB, "color": WHITE, "sz": 17, "spcAft": 3},
            {"t": "Главный специалист"}, {"t": "Отдел продаж", "spcAft": 8},
            {"t": "Тел.: внутренний 1234", "color": MUTED, "sz": 13}], sz=14.5, color=TEXT, lnsp=1.0)
    s.end(anim=300)
    note(s, MX, 5.82, CW, "Подпись — это визитка. Без лишнего: не нужны цитаты, цветные шрифты и картинки.", icon="lightbulb", anim=600)

    # ------------------------------------------------------------------ before you hit Send
    s = k.slide("m2-check", title="Перед тем как нажать «Отправить»", sub="Пять секунд на проверку экономят час на исправление", glow="b",
                notes="Перед отправкой проверьте пять вещей. Адресаты — те, кто нужно. Тема отражает суть. Вложение на месте, и это нужный файл. "
                      "Тон вежливый. И нет ошибок — проверку правописания запускает клавиша Эф семь.")
    rows(s, MX, 2.2, 7.4,
         [("users", "Адресаты", "Те, кто нужно? Автоподстановка могла выбрать однофамильца."),
          ("type", "Тема", "Отражает суть письма."),
          ("paperclip", "Вложение", "Прикреплено — и это нужный файл."),
          ("smile", "Тон", "Вежливо, без КАПСЛОКА и «!!!»."),
          ("file-check", "Ошибки", "Проверка правописания — клавиша F7.")], rh=0.64, tw=1.55, bsz=13.5)
    cx, cw = MX + 7.75, CW - 7.75
    s.begin("recall")
    s.rrect(cx, 2.2, cw, 3.6, r=0.26, fill="glass", line="glass")
    s.pic(ic("undo-2"), cx + 0.3, 2.48, w=0.46)
    s.text(cx + 0.3, 3.08, cw - 0.6, 0.72, "Отправили по ошибке?", sz=17, color=WHITE, font=FONT_SB, lnsp=0.98)
    s.line(cx + 0.3, 3.62, cx + cw - 0.3, 3.62, color=(WHITE, 20))
    s.text(cx + 0.3, 3.76, cw - 0.6, 1.95,
           [{"t": "Откройте письмо в «Отправленных» двойным щелчком → **«Действия»** → **«Отозвать сообщение»**.", "spcAft": 6},
            {"t": "Сработает, только если получатель в банке и ещё не открыл письмо.", "color": MUTED}], sz=13, color=TEXT, lnsp=1.0)
    s.end(anim=520)

    # ------------------------------------------------------------------ check yourself
    quiz(k, "m2-q1", "В какое поле поставить адрес коллеги?",
         ["«Кому»", "«Копия»", "«Скрытая копия»"], 1,
         "«Копия» — для тех, кому письмо нужно для сведения. А руководителя ставим в «Кому»: от него вы ждёте действия.",
         situation="Вы отправляете отчёт руководителю на согласование. Коллега из соседнего отдела должен быть в курсе, но отвечать ему не нужно.",
         tag="Проверьте себя · вопрос 1 из 2")
    quiz(k, "m2-q2", "Какую кнопку нажать?",
         ["«Ответить»", "«Ответить всем»", "«Переслать»"], 0,
         "«Спасибо» нужно только отправителю. «Ответить всем» отвлекло бы ещё тридцать человек.",
         situation="Вам пришло письмо, в копии которого ещё 30 сотрудников. Вы хотите поблагодарить отправителя.",
         tag="Проверьте себя · вопрос 2 из 2")
