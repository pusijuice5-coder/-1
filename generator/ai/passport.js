function cell(text, w, o = {}) {
  const paras = (Array.isArray(text) ? text : [text]).map((t) => new Paragraph({
    children: runs(t, { size: o.size || 18, color: o.head ? "FFFFFF" : (o.color || BODY), bold: o.head || o.bold }),
    spacing: { after: 40, line: 252 }, alignment: o.align,
  }));
  return new TableCell({
    width: { size: w, type: WidthType.DXA }, borders, children: paras,
    shading: o.head ? { fill: DARK, type: ShadingType.CLEAR, color: "auto" } : o.fill ? { fill: o.fill, type: ShadingType.CLEAR, color: "auto" } : undefined,
    margins: { top: 70, bottom: 70, left: 110, right: 110 },
  });
}
function table(widths, head, rows, o = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const trs = [];
  if (head) trs.push(new TableRow({ tableHeader: true, children: head.map((h, i) => cell(h, widths[i], { head: true })) }));
  rows.forEach((r, k) => trs.push(new TableRow({
    cantSplit: true,
    children: r.map((c, i) => cell(c, widths[i], { fill: o.firstColFill && i === 0 ? MINT : (o.zebra && k % 2 ? "F5F9F6" : undefined),
      bold: o.firstColBold && i === 0, align: o.center && o.center.includes(i) ? AlignmentType.CENTER : undefined })),
  })));
  return new Table({ width: { size: total, type: WidthType.DXA }, columnWidths: widths, rows: trs });
}
