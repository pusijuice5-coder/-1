hits = {k: 0 for k in M}
def fix(m):
    para = m.group(0)
    ts = list(re.finditer(r'(<w:t(?: [^>]*)?>)([^<]*)(</w:t>)', para))
    txt = "".join(t.group(2) for t in ts)
    key = txt.strip()
    if key not in M:
        return para
    hits[key] += 1
    new = M[key]
    out, last = [], 0
    for i, t in enumerate(ts):
        out.append(para[last:t.start()])
        open_tag = t.group(1)
        if 'xml:space' not in open_tag:
            open_tag = open_tag.replace('<w:t', '<w:t xml:space="preserve"', 1)
        out.append(open_tag + (escape(new) if i == 0 else "") + t.group(3))
        last = t.end()
    out.append(para[last:])
    return "".join(out)
x = re.sub(r'<w:p[ >].*?</w:p>', fix, x, flags=re.S)
