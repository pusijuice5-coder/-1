# -*- coding: utf-8 -*-
"""AI course - module 4 (prompting) and module 5 (verification and responsibility)."""
from tpl_ai import *

RED, YEL = "D64545", "F2C94C"


def build(d):
    # ================= MODULE 4
    module_cover(d, 4, "Как ставить задачи ИИ",
                 ["Промпт — задание для ИИ", "Формула запроса из 5 элементов", "Было → стало: улучшаем запрос",
                  "Приёмы, которые улучшают ответ", "Сценарии для работы в банке"],
                 "В четвёртом модуле научимся ставить задачи ИИ так, чтобы с первого раза получать полезный результат, — и при этом "
                 "не передавать лишних данных.")

    talk(d, "Представьте, что ИИ — новый стажёр: очень быстрый и начитанный, но ничего не знает о вашей задаче.\n"
            "Чем понятнее задание, тем лучше результат. Такое задание называют **промптом**.",
         notes=("Представьте, что ИИ — это новый стажёр: очень быстрый и начитанный, но он ничего не знает ни о вас, ни о банке, ни о "
                "вашей задаче. Если сказать ему «напиши письмо», он напишет что-то общее. Чем понятнее задание, тем лучше результат. "
                "Задание для ИИ называют промптом. Давайте разберём, как его составить."), pose="present")

    # ---- formula
    s = d.new(bg="flight", notes=(
        "Хороший запрос состоит из пяти элементов. Роль: кем должен выступить ИИ — например, опытным редактором деловых писем. Задача: "
        "что именно нужно сделать. Контекст: для кого и зачем — без персональных данных и банковской тайны. Формат: в каком виде нужен "
        "ответ — список, таблица, письмо, какой объём. Ограничения: тон, язык, чего избегать. Не обязательно использовать все пять "
        "элементов каждый раз, но чем больше их в запросе, тем точнее ответ."))
    s.title("Формула запроса: 5 элементов", anim=0)
    s.subtitle("Роль + Задача + Контекст + Формат + Ограничения", anim=100)
    parts = [("Роль", "Кем выступить ИИ", "«Ты — опытный редактор деловых писем»"),
             ("Задача", "Что сделать", "«Составь ответ на жалобу клиента»"),
             ("Контекст", "Для кого и зачем — без персональных данных", "«Списание было ошибочным, деньги уже вернули»"),
             ("Формат", "Вид и объём ответа", "«Письмо до 120 слов, 3 абзаца»"),
             ("Ограничения", "Тон, язык, чего избегать", "«Вежливо, без канцелярита, на русском»")]
    cols = [DARK, G1, G2, G3, G4]
    s.line(1.3, 2.38, 12.0, 2.38, color=G4, lw=2.5, dash="dash")
    for i, (h, sub, ex) in enumerate(parts):
        x = 0.55 + i * 2.48
        s.begin(h)
        s.hexnum(x + 0.42, 1.9, 1.4, i + 1, fill=cols[i], sz=26)
        card(s, x, 3.05, 2.3, 3.75)
        s.text(x + 0.2, 3.2, 1.9, 0.45, h, sz=18, bold=True, color=TITLE)
        s.text(x + 0.2, 3.7, 1.9, 0.8, sub, sz=12.5, color=MUTED, lnsp=1.0)
        s.rrect(x + 0.15, 4.65, 2.0, 1.95, r=0.18, fill=MINT)
        s.text(x + 0.3, 4.75, 1.7, 1.75, ex, sz=12.5, color=DARK, lnsp=1.05, anchor="ctr")
        s.end(anim=200 + i * 150)

    # ---- before / after
    s = d.new(bg="flight", notes=(
        "Сравним два запроса. Слабый: «Напиши письмо клиенту». ИИ не знает, о чём письмо, кому и в каком тоне — и ответ получится "
        "общим. Сильный запрос содержит все пять элементов: роль, задачу, контекст, формат и ограничения. При этом в нём нет ни имени "
        "клиента, ни номера карты, ни суммы — они не нужны, чтобы получить хороший текст. Имя и детали вы добавите сами, уже в "
        "банковской системе."))
    s.title("Было → стало: улучшаем запрос", anim=0)
    s.begin("Слабый")
    s.rrect(0.55, 1.35, 4.3, 5.5, r=0.22, fill=WHITE, shadow="soft")
    s.chip(0.8, 1.6, 1.9, 0.38, "СЛАБЫЙ ЗАПРОС", fill=GREY, color=DARK, sz=11)
    s.rrect(0.8, 2.25, 3.8, 1.0, r=0.2, fill="F2F4F3", text="«Напиши письмо клиенту»", sz=17, bold=True, color=TITLE, anchor="ctr",
            align="ctr")
    bullets(s, 0.85, 3.55, 3.75, 3.1, ["Непонятно, о чём письмо и кому", "Нет тона, формата и объёма", "Результат — общий текст, "
                                                                                                    "который придётся переписывать"],
            sz=14, spc=10, bcolor=MUTED)
    s.end(anim=100)
    s.shape(5.0, 3.75, 0.42, 0.55, geom="chevron", fill=G2, anim=300)
    s.begin("Сильный")
    card(s, 5.6, 1.35, 7.15, 5.5, dark=True)
    s.chip(5.85, 1.6, 2.1, 0.38, "СИЛЬНЫЙ ЗАПРОС", fill=LIME, color=DARK, sz=11)
    rows = [("РОЛЬ", "Ты — опытный специалист клиентского сервиса банка."),
            ("ЗАДАЧА", "Составь ответ на жалобу клиента."),
            ("КОНТЕКСТ", "Клиент жалуется на ошибочное списание с карты. Мы проверили: это был технический сбой, деньги уже вернули."),
            ("ФОРМАТ", "Письмо до 120 слов: извинение, объяснение, что сделано."),
            ("ОГРАНИЧЕНИЯ", "Вежливо и просто, без канцелярита и обещаний компенсаций.")]
    y = 2.25
    for i, (k, v) in enumerate(rows):
        h = max(0.5, text_height([{"runs": parse_runs(v)}], 5.0, 13.5, False, 1.0) + 0.08)
        s.chip(5.85, y + 0.08, 1.55, 0.34, k, fill=[DARK, G1, G2, G3, G4][i] if i else "2E5A41", color=WHITE, sz=9.5)
        s.text(7.55, y, 5.0, h, v, sz=13.5, color=WHITE, lnsp=1.0)
        y += h + 0.2
    s.end(anim=500)
    s.rrect(5.85, 6.15, 6.65, 0.5, r=0.25, fill="16402A", text=[{"t": "**Ни имени, ни номера карты, ни суммы** — они не нужны для хорошего текста",
                                                                "bcolor": LIME}], sz=12, color=WHITE, anchor="ctr", align="ctr", anim=900)

    # ---- techniques
    s = d.new(bg="flight_l", notes=(
        "Несколько приёмов, которые заметно улучшают ответ. Итерируйте: первый ответ — это черновик, просите сократить, упростить, "
        "добавить пример. Давайте образец текста, стиль которого нужно повторить, — конечно, без конфиденциальных данных. Попросите ИИ "
        "сначала задать вам уточняющие вопросы. Разбивайте сложную задачу на шаги. Просите указать источники и отметить, в чём ИИ не "
        "уверен. И начинайте новый чат для новой темы, чтобы старый контекст не мешал."))
    s.title("Приёмы, которые улучшают ответ", anim=0)
    tips = [("Итерируйте", "Первый ответ — черновик. «Сократи вдвое», «Сделай проще», «Добавь пример»"),
            ("Дайте образец", "«Напиши в стиле этого текста: …» — образец без конфиденциальных данных"),
            ("Пусть ИИ спросит", "«Прежде чем ответить, задай мне 3 уточняющих вопроса»"),
            ("Разбивайте на шаги", "Сначала план, потом каждый раздел. Сложное — по частям"),
            ("Просите источники", "«Укажи источники и отметь, в чём не уверен» — и проверяйте их"),
            ("Новый чат — новая тема", "Старый контекст может мешать и смешивать задачи")]
    for i, (h, t) in enumerate(tips):
        x = 0.55 + (i % 3) * 4.15
        y = 1.35 + (i // 3) * 2.75
        s.begin(h)
        card(s, x, y, 3.95, 2.5)
        s.hexnum(x + 0.25, y + 0.25, 0.95, i + 1, fill=G2 if i % 2 else DARK, sz=18)
        s.text(x + 1.4, y + 0.25, 2.4, 0.64, h, sz=16, bold=True, color=TITLE, anchor="ctr", lnsp=0.95)
        s.text(x + 0.3, y + 1.15, 3.4, 1.25, t, sz=13.5, color=BODY, lnsp=1.05)
        s.end(anim=150 + i * 120)

    # ---- scenarios
    s = d.new(bg="flight", notes=(
        "Вот примеры задач, с которыми ИИ помогает сотрудникам банка. Обратите внимание на цвет каждой задачи по светофору данных. "
        "Зелёные можно выполнять в разрешённых банком инструментах. Жёлтые, например краткое содержание внутреннего регламента, — только "
        "в корпоративном ИИ. А там, где нужны данные клиентов, используйте вымышленный пример: формулу для Excel можно отработать на "
        "придуманных цифрах, а потом применить к реальной таблице в банковской системе."))
    s.title("Сценарии для работы в банке", anim=0)
    sc = [("Клиентский сервис", "Черновик ответа на типовую жалобу — по обезличенному описанию", "3E9A4E"),
          ("Маркетинг и продажи", "Идеи и тексты для акции по опубликованным тарифам", "3E9A4E"),
          ("HR и обучение", "План адаптации, вопросы для теста, текст вакансии", "3E9A4E"),
          ("Аналитика", "Формула Excel — на вымышленных данных, без выгрузки клиентов", "3E9A4E"),
          ("Любой отдел", "Краткое содержание внутреннего регламента — только в корпоративном ИИ", YEL),
          ("IT", "Объяснить ошибку или подход — без исходного кода и настроек систем банка", YEL)]
    for i, (h, t, c) in enumerate(sc):
        x = 0.55 + (i % 2) * 6.2
        y = 1.35 + (i // 2) * 1.45
        s.begin(h)
        card(s, x, y, 6.0, 1.3)
        s.rect(x, y + 0.2, 0.09, 0.9, fill=c)
        s.text(x + 0.35, y + 0.15, 4.2, 0.4, h, sz=15, bold=True, color=TITLE)
        s.text(x + 0.35, y + 0.55, 5.4, 0.7, t, sz=12.5, color=BODY, lnsp=1.0)
        s.chip(x + 4.45, y + 0.17, 1.35, 0.32, "ЗЕЛЁНЫЙ" if c != YEL else "ЖЁЛТЫЙ", fill=c, color=WHITE if c != YEL else DARK, sz=9.5)
        s.end(anim=150 + i * 110)
    s.rrect(0.55, 5.85, 12.2, 1.0, r=0.25, fill=DARK, text=[{"t": "Нужны данные клиентов? Отработайте запрос на **вымышленном примере**, а результат "
                                                            "примените к реальным данным уже в банковской системе.", "bcolor": LIME}],
            sz=14, color=WHITE, anchor="ctr", inset=(0.4, 0, 0.4, 0), lnsp=1.05, anim=900)

    # ---- practice
    s = d.new(bg="flight", notes=(
        "Практика. Задача: нужно подготовить для клиентов короткую памятку о том, как распознать мошеннический звонок. Поставьте видео на "
        "паузу и составьте запрос по формуле из пяти элементов. Затем сравните с примером. Ваш вариант может отличаться — главное, чтобы "
        "в нём были роль, задача, контекст, формат и ограничения и не было персональных данных."))
    s.title("Практика: составьте запрос", anim=0)
    s.begin("Задание")
    card(s, 0.55, 1.35, 5.2, 5.5, dark=True)
    s.chip(0.85, 1.65, 1.6, 0.38, "ЗАДАНИЕ", fill=LIME, color=DARK, sz=11)
    s.text(0.85, 2.25, 4.6, 2.0, "Подготовьте для клиентов короткую памятку: как распознать мошеннический звонок «из банка».",
           sz=18, bold=True, color=WHITE, lnsp=1.05)
    s.text(0.85, 4.3, 4.6, 2.3, ["Составьте запрос по формуле из 5 элементов.", "Поставьте паузу, напишите свой вариант — затем сравните "
                                                                                "с примером."],
           sz=14, color="D8E8DC", lnsp=1.05, spc_after=8)
    s.end(anim=100)
    s.begin("Пример")
    card(s, 6.0, 1.35, 6.75, 5.5)
    s.chip(6.3, 1.65, 2.6, 0.38, "ПРИМЕР ЗАПРОСА", fill=G2, sz=11)
    ex = [("Роль", "Ты — специалист по финансовой безопасности банка."),
          ("Задача", "Подготовь памятку для клиентов о мошеннических звонках."),
          ("Контекст", "Мошенники представляются сотрудниками банка и выманивают коды из SMS."),
          ("Формат", "5 признаков обмана и 3 правила, что делать. До 120 слов, списком."),
          ("Ограничения", "Простой язык, без терминов и запугивания.")]
    y = 2.25
    for i, (k, v) in enumerate(ex):
        s.text(6.3, y, 1.7, 0.75, k, sz=13, bold=True, color=G1, lnsp=1.0)
        s.text(8.0, y, 4.5, 0.75, v, sz=13, color=BODY, lnsp=1.0)
        y += 0.88
    s.end(anim=2500)

    opts = ["«Напиши памятку про мошенников»",
            "«Ты — специалист по безопасности банка. Подготовь для клиентов памятку: 5 признаков мошеннического звонка и что делать. "
            "Простой язык, до 120 слов, списком»",
            "«Вот случай клиента Н. Юсуповой, карта 8600…: её обманули по телефону. Напиши памятку на основе этого случая»",
            "«Напиши максимально подробно всё, что знаешь о мошенничестве»"]
    quiz_wide(d, "Нужно подготовить для клиентов памятку о мошеннических звонках. Коллеги предлагают разные запросы к ИИ.",
              "Какой запрос лучше?", opts, 1)
    review(d, 4, ["«Напиши памятку про мошенников»", "Роль + задача + формат + ограничения", "Случай клиента с ФИО и картой",
                  "«Всё, что знаешь о мошенничестве»"],
           ["Слишком общий запрос: ни аудитории, ни формата, ни объёма.",
            "Все элементы формулы — и ни одного лишнего персонального данного.",
            "ФИО и номер карты — «красная» зона. Для памятки они не нужны.",
            "Нет фокуса и формата: получится длинный текст, который придётся переписывать."], 1,
           "Верный ответ — Б. В нём есть роль, задача, аудитория, формат и ограничения, и нет персональных данных. Вариант В нарушает "
           "правила информационной безопасности: имя клиента и номер карты нельзя передавать в ИИ, да и для памятки они не нужны.")
    summary(d, 4, ["Промпт — это задание. Чем оно понятнее, тем лучше результат.",
                   "Формула: роль + задача + контекст + формат + ограничения. Контекст — без персональных данных.",
                   "Первый ответ — черновик: уточняйте, давайте образец, разбивайте на шаги."],
            "Далее: Модуль 5. Проверка результата",
            "Итоги четвёртого модуля. Промпт — это задание для ИИ, и чем оно понятнее, тем лучше результат. Используйте формулу из пяти "
            "элементов: роль, задача, контекст, формат и ограничения, — а контекст давайте без персональных данных. Первый ответ — "
            "черновик: уточняйте и улучшайте. Далее — как проверять результат.")

    # ================= MODULE 5
    module_cover(d, 5, "Проверка результата и ответственность",
                 ["Почему ответ ИИ нужно проверять", "Чек-лист проверки", "Уровень риска и роль человека", "Ответственность и этика",
                  "Когда ИИ не подходит"],
                 "Пятый модуль — о том, как проверять результат работы ИИ и кто за него отвечает.", pose="wave")

    talk(d, "ИИ может уверенно сослаться на закон, которого нет, или привести цифру, которую никто не публиковал.\n"
            "Звучит убедительно — но **убедительно не значит верно**.",
         notes=("ИИ может уверенно сослаться на закон, которого не существует, или привести цифру, которую никто не публиковал. Такие "
                "ошибки называют галлюцинациями. Звучит убедительно — но убедительно не значит верно. Поэтому любой результат ИИ, "
                "который уходит дальше вашего черновика, нужно проверять."), pose="chest")

    # ---- checklist
    s = d.new(bg="flight_l", notes=(
        "Перед тем как использовать результат ИИ, пройдитесь по короткому чек-листу. Факты и цифры — сверьте с первоисточником. Ссылки и "
        "нормы права — откройте и проверьте, законы — по национальной базе законодательства. Расчёты — пересчитайте сами. Соответствие — "
        "ответ должен соответствовать продуктам, тарифам и правилам банка. Конфиденциальность — убедитесь, что в тексте нет лишних "
        "данных. И последний вопрос: готовы ли вы подписать это своим именем?"))
    s.title("Чек-лист проверки ответа ИИ", anim=0)
    chk = [("Факты и цифры", "Сверьте с первоисточником"),
           ("Ссылки и нормы права", "Откройте каждую ссылку, законы — на lex.uz"),
           ("Расчёты", "Пересчитайте сами или в Excel"),
           ("Соответствие банку", "Продукты, тарифы, регламенты — актуальные и наши"),
           ("Конфиденциальность", "В тексте нет лишних данных клиентов и банка"),
           ("Своё имя", "Готовы подписать этот результат своим именем?")]
    for i, (h, t) in enumerate(chk):
        x = 0.55 + (i // 3) * 6.2
        y = 1.4 + (i % 3) * 1.8
        s.begin(h)
        s.rrect(x + 0.45, y, 5.55, 1.5, r=0.3, fill=WHITE if i != 5 else DARK, shadow="pill")
        s.text(x + 1.6, y + 0.22, 4.2, 0.45, h, sz=17, bold=True, color=TITLE if i != 5 else LIME)
        s.text(x + 1.6, y + 0.7, 4.2, 0.65, t, sz=13.5, color=BODY if i != 5 else WHITE, lnsp=1.0)
        s.hexnum(x, y + 0.28, 1.4, i + 1, fill=G2 if i != 5 else LIME, color=WHITE if i != 5 else DARK, sz=24)
        s.end(anim=150 + i * 120)

    # ---- risk levels
    s = d.new(bg="flight", notes=(
        "Глубина проверки зависит от риска. Низкий риск — идеи, черновик внутреннего письма, план встречи: достаточно прочитать и "
        "поправить. Средний риск — тексты для клиентов, отчёты, презентации для руководства: тщательная проверка фактов и согласование "
        "по обычным правилам. Высокий риск — решения о клиентах, кредитах, блокировках, юридические и комплаенс-вопросы: здесь ИИ может "
        "быть только помощником, а решение принимает человек по утверждённой процедуре банка."))
    s.title("Уровень риска определяет глубину проверки", anim=0)
