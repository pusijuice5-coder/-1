# -*- coding: utf-8 -*-
"""AI course - module 2 (tools) and module 3 (information security rules)."""
from tpl_ai import *


def build(d):
    # ================= MODULE 2
    module_cover(d, 2, "ИИ-ассистенты: обзор инструментов",
                 ["Популярные ИИ-ассистенты", "Как выбрать инструмент под задачу", "Публичный и корпоративный ИИ",
                  "«Теневой ИИ» и главное правило выбора"],
                 "Во втором модуле познакомимся с самыми известными ИИ-ассистентами, разберёмся, чем они отличаются, и поймём главное: "
                 "чем публичный ИИ отличается от корпоративного и какими инструментами можно пользоваться в работе.", pose="wave")

    # ---- popular assistants
    s = d.new(bg="flight", notes=(
        "Вот самые известные ИИ-ассистенты. ChatGPT от компании OpenAI — универсальный помощник для текстов, анализа файлов и изображений. "
        "Claude от компании Anthropic хорошо работает с длинными документами, аккуратно пишет и помогает с анализом и программированием. "
        "Gemini от Google интегрирован с сервисами Google и умеет работать с поиском, фото и видео. Microsoft Copilot встроен в Windows, "
        "браузер Edge и офисные программы Microsoft 365. Perplexity — это ИИ-поиск, который даёт ответы со ссылками на источники. "
        "DeepSeek — китайская компания с открытыми моделями; данные её публичного сервиса хранятся в Китае. Есть и другие ассистенты. "
        "Их возможности меняются каждые несколько месяцев, поэтому важно помнить не версии, а правила безопасной работы."))
    s.title("Популярные ИИ-ассистенты", anim=0)
    tools = [("C", "ChatGPT", "OpenAI · США", "Универсальный помощник: тексты, анализ файлов, изображения, голосовой режим"),
             ("Cl", "Claude", "Anthropic · США", "Длинные документы, аккуратные тексты, анализ и программирование"),
             ("G", "Gemini", "Google · США", "Связка с сервисами Google, работа с поиском, фото и видео"),
             ("Co", "Microsoft Copilot", "Microsoft · США", "Встроен в Windows, Edge и Microsoft 365: Word, Excel, Outlook, Teams"),
             ("P", "Perplexity", "Perplexity AI · США", "ИИ-поиск: ответы со ссылками на источники"),
             ("D", "DeepSeek", "DeepSeek · Китай", "Открытые модели; данные публичного сервиса хранятся в Китае")]
    for i, (ab, n, org, t) in enumerate(tools):
        x = 0.55 + (i % 3) * 4.15
        y = 1.35 + (i // 3) * 2.45
        s.begin(n)
        card(s, x, y, 3.95, 2.25)
        icon_circle(s, x + 0.25, y + 0.25, 0.75, ab, fill=DARK if i != 5 else G5, sz=16)
        s.text(x + 1.2, y + 0.22, 2.6, 0.45, n, sz=17, bold=True, color=TITLE)
        s.text(x + 1.2, y + 0.65, 2.6, 0.32, org, sz=11, color=MUTED)
        s.text(x + 0.3, y + 1.15, 3.4, 1.0, t, sz=12.5, color=BODY, lnsp=1.05)
        s.end(anim=150 + i * 120)
    s.text(0.55, 6.3, 12.2, 0.6, "Есть и другие: GigaChat, YandexGPT, Mistral, Llama… Возможности и версии меняются каждые несколько месяцев — "
                                 "запоминайте не названия моделей, а **правила безопасной работы**.", sz=13, color=BODY, lnsp=1.05, anim=900)

    # ---- choosing a tool
    s = d.new(bg="flight", notes=(
        "Как выбрать инструмент под задачу? Для текстов подойдёт любой разрешённый ассистент. Для разбора длинного документа нужен "
        "ассистент с большим объёмом контекста. Для поиска информации — режим поиска со ссылками, но ссылки обязательно открыть и проверить. "
        "Для работы в Word, Excel и Outlook — Copilot в Microsoft 365, если банк его подключил. Для изображений — генераторы картинок, с "
        "учётом авторских прав. И главный критерий: не какой ассистент умнее, а какой разрешён банком для ваших данных."))
    s.title("Как выбрать инструмент под задачу", anim=0)
    rows = [("Написать или отредактировать текст", "Любой ИИ-ассистент, разрешённый банком"),
            ("Разобрать длинный документ", "Ассистент с большим «окном контекста» (например, Claude, Gemini)"),
            ("Найти информацию с источниками", "ИИ-поиск (Perplexity, режимы поиска в ChatGPT и Gemini) — ссылки проверяем"),
            ("Работать в Word, Excel, Outlook", "Copilot в Microsoft 365 — если подключён в банке"),
            ("Картинка для презентации", "Генераторы изображений — с учётом авторских прав и без фото людей и документов")]
    s.chip(0.55, 1.3, 4.6, 0.46, "ЗАДАЧА", fill=DARK, sz=12)
    s.chip(5.45, 1.3, 7.3, 0.46, "ЧТО ПОДОЙДЁТ", fill=G2, sz=12)
    for i, (a, b) in enumerate(rows):
        y = 1.95 + i * 0.84
        s.begin("Строка %d" % (i + 1))
        s.rrect(0.55, y, 4.6, 0.72, r=0.2, fill=WHITE, shadow="soft", text=a, sz=13.5, bold=True, color=TITLE, anchor="ctr",
                inset=(0.25, 0, 0.15, 0), lnsp=1.0)
        s.rrect(5.45, y, 7.3, 0.72, r=0.2, fill="EEF7F0", text=b, sz=13, color=BODY, anchor="ctr", inset=(0.25, 0, 0.15, 0), lnsp=1.0)
        s.end(anim=150 + i * 120)
    s.rrect(0.55, 6.3, 12.2, 0.7, r=0.25, fill=DARK, text=[{"t": "Главный критерий — не «какой умнее», а **«какой разрешён банком для этих данных»**",
                                                          "bcolor": LIME}], sz=15, color=WHITE, align="ctr", anchor="ctr", anim=900)

    # ---- public vs corporate
    s = d.new(bg="flight", notes=(
        "Важно различать публичный и корпоративный ИИ. Публичный — это сервис, которым вы пользуетесь через личный аккаунт, бесплатно или по "
        "личной подписке. Ваши данные уходят поставщику, хранятся за рубежом и, в зависимости от настроек сервиса, могут использоваться для "
        "обучения моделей. Банк это не контролирует. Корпоративный ИИ одобрен банком: есть договор о защите данных, данные не используются для "
        "обучения, вход — через корпоративную учётную запись, а служба информационной безопасности контролирует работу."))
    s.title("Публичный и корпоративный ИИ", anim=0)
    pub = ["Личный аккаунт, бесплатно или по личной подписке", "Данные уходят поставщику и хранятся за рубежом",
           "Переписка может использоваться для обучения моделей (зависит от настроек)", "Банк не контролирует, где и сколько хранятся данные"]
    corp = ["Инструмент одобрен банком, вход по корпоративной учётной записи", "Договор с поставщиком о защите и хранении данных",
            "Данные не используются для обучения моделей", "Контроль и журналирование со стороны службы ИБ"]
    for j, (h, sub, items, dark) in enumerate([("ПУБЛИЧНЫЙ ИИ", "личный аккаунт", pub, False), ("КОРПОРАТИВНЫЙ ИИ", "одобрен банком", corp, True)]):
        x = 0.55 + j * 6.25
        s.begin(h)
        card(s, x, 1.35, 5.95, 5.5, dark=dark)
        s.text(x + 0.35, 1.6, 5.3, 0.55, h, sz=22, bold=True, color=LIME if dark else DARK)
        s.chip(x + 0.35, 2.2, 2.1, 0.38, sub, fill=G2 if dark else GREY, color=WHITE if dark else DARK, sz=11)
        for i, t in enumerate(items):
            y = 2.85 + i * 0.95
            if dark:
                check_icon(s, x + 0.35, y + 0.12, 0.46, fill=G2)
            else:
                cross_icon(s, x + 0.35, y + 0.12, 0.46)
            s.text(x + 1.0, y, 4.7, 0.75, t, sz=14, color=WHITE if dark else BODY, anchor="ctr", lnsp=1.0)
        s.end(anim=150 + j * 300)

    # ---- shadow AI
    def shadow(s, ytop):
        y = max(ytop + 0.3, 3.75)
        ex = ["Личный аккаунт в чат-боте", "ИИ-расширения в браузере", "Боты в мессенджерах", "ИИ-функции в личных приложениях"]
        for i, t in enumerate(ex):
            x = 0.7 + (i % 2) * 2.95
            yy = y + (i // 2) * 1.2
            s.begin("Пример %d" % (i + 1))
            s.rrect(x, yy, 2.8, 1.05, r=0.2, fill=DARK, shadow="green")
            s.text(x + 0.2, yy, 2.4, 1.05, t, sz=13, bold=True, color=WHITE, anchor="ctr", lnsp=1.0)
            s.end(anim=500 + i * 120)
    talk(d, "«Теневой ИИ» — это сервисы, о которых не знает служба ИБ.\nДаже с хорошими намерениями: банк не может защитить данные, "
            "которые туда ушли.",
         notes=("Есть понятие «теневой ИИ». Это ИИ-сервисы, которыми сотрудники пользуются без ведома службы информационной безопасности: "
                "личный аккаунт в чат-боте, расширение в браузере, бот в мессенджере, ИИ-функции в личных приложениях — например, "
                "переводчик или распознавание фото документов. Даже если намерения хорошие, банк не может защитить данные, которые туда ушли."),
         pose="present", extra=shadow)

    # ---- the rule
    s = d.new(bg="fdark", notes=(
        "Отсюда главное правило выбора. В работе мы пользуемся только ИИ-инструментами, разрешёнными банком, и только под корпоративной "
        "учётной записью. Актуальный перечень разрешённых инструментов ведёт служба информационной безопасности. Если инструмента нет в "
        "перечне — для рабочих данных его не используем. Сомневаетесь — спросите службу ИБ до того, как отправить данные, а не после."))
    s.ezoza("present", right=13.25, h=7.0)
    s.text(0.55, 0.7, 7.3, 0.45, "ГЛАВНОЕ ПРАВИЛО ВЫБОРА", sz=16, bold=True, color=LIME, anim=0)
    s.text(0.55, 1.25, 7.4, 2.4, "В работе — только ИИ-инструменты, разрешённые банком, и только под корпоративной учётной записью",
           sz=30, bold=True, color=WHITE, lnsp=0.95, anim=150)
    for i, t in enumerate(["Актуальный перечень разрешённых инструментов ведёт служба информационной безопасности",
                           "Нет в перечне — для рабочих данных не используем",
                           "Сомневаетесь — спросите ИБ **до** отправки данных, а не после"]):
        y = 4.05 + i * 0.95
        s.begin("Пункт %d" % (i + 1))
        s.rrect(0.95, y, 6.7, 0.8, r=0.3, fill=WHITE, shadow="pill")
        s.text(1.95, y, 5.55, 0.8, t, sz=13.5, color="2B3A33", anchor="ctr", lnsp=1.0)
        s.hexnum(0.45, y - 0.02, 1.2, i + 1, fill=G2, sz=20)
        s.end(anim=400 + i * 150)

    opts = ["Установить: это просто экономит время", "Установить, но не открывать письма с данными клиентов",
            "Не устанавливать без согласования с ИБ: расширение получает доступ ко всему, что открыто в браузере",
            "Сначала установить на компьютер коллеги и посмотреть, что будет"]
    quiz(d, 2, "Коллега советует удобное браузерное расширение: оно само пересказывает любые открытые страницы и письма с помощью ИИ. "
               "Установка — в один клик.", "Как поступить?", opts, 2)
    review(d, 2, opts,
           ["Экономия времени не оправдывает передачу данных неизвестному сервису.",
            "Расширение видит всё в браузере — даже то, что вы не собирались ему показывать.",
            "Любые ИИ-расширения и приложения — только после согласования со службой ИБ.",
            "Риск для данных остаётся тем же, просто на другом компьютере."], 2,
           "Верный ответ — В. ИИ-расширения браузера получают доступ ко всему, что вы открываете: почте, внутренним системам, документам. "
           "Поэтому любые такие расширения, боты и приложения устанавливаются только после согласования со службой информационной безопасности.")
    summary(d, 2, ["ChatGPT, Claude, Gemini, Copilot и другие решают похожие задачи, а их версии быстро меняются.",
                   "Публичный ИИ — данные уходят поставщику. Корпоративный — под защитой договора и контролем ИБ.",
                   "В работе — только инструменты из перечня банка и корпоративная учётная запись."],
            "Далее: Модуль 3. Правила ИБ при работе с ИИ",
            "Итоги второго модуля. Популярные ИИ-ассистенты решают похожие задачи, а их версии быстро меняются. Публичный ИИ передаёт данные "
            "поставщику, корпоративный работает под защитой договора и контролем службы ИБ. В работе мы используем только разрешённые банком "
            "инструменты. Переходим к ключевому модулю — правилам информационной безопасности.")

    # ================= MODULE 3
    module_cover(d, 3, "Информационная безопасность при работе с ИИ",
                 ["Почему это важно для банка", "«Светофор данных»", "Как обезличивать информацию", "ИИ-мошенничество и дипфейки",
                  "Что делать при инциденте"],
                 "Третий модуль — ключевой в курсе. Разберём, почему безопасность данных при работе с ИИ так важна для банка, научимся "
                 "определять, какие данные можно передавать ИИ, а какие нельзя, и узнаем, как распознать ИИ-мошенничество.")

    # ---- why it matters
    s = d.new(bg="flight", notes=(
        "Почему это так важно? Когда вы отправляете текст в публичный ИИ-сервис, вы передаёте его третьей стороне — как правило, на серверы "
        "за рубежом. Отправленное нельзя вернуть. Последствия могут ударить по клиенту — утечка его данных и риск мошенничества; по банку — "
        "штрафы, проверки, потеря доверия; и по самому сотруднику — дисциплинарная и иная ответственность, предусмотренная законом. "
        "Правила работы с данными закреплены в законодательстве Узбекистана, в том числе в законах «О персональных данных» и «О банковской "
        "тайне», а также во внутренних политиках информационной безопасности банка."))
    s.title("Почему это важно для банка", anim=0)
    s.begin("Отправленное не вернуть")
    card(s, 0.55, 1.35, 12.2, 1.35, dark=True)
    s.text(0.85, 1.35, 11.6, 1.35, [{"t": "Запрос в публичный ИИ = передача данных третьей стороне, как правило, за рубеж. **Отправленное нельзя вернуть.**",
                                     "bcolor": LIME}], sz=18, color=WHITE, anchor="ctr", lnsp=1.05)
    s.end(anim=100)
    cons = [("Для клиента", "Утечка личных и финансовых данных, риск мошенничества"),
            ("Для банка", "Штрафы, проверки регулятора, потеря доверия клиентов и репутации"),
            ("Для сотрудника", "Дисциплинарная и иная ответственность, предусмотренная законом")]
    for i, (h, t) in enumerate(cons):
        x = 0.55 + i * 4.15
        s.begin(h)
        card(s, x, 2.95, 3.95, 2.0)
        s.hexnum(x + 0.25, 3.15, 0.85, i + 1, fill=G2, sz=16)
        s.text(x + 1.25, 3.15, 2.55, 0.57, h, sz=17, bold=True, color=TITLE, anchor="ctr")
        s.text(x + 0.3, 3.9, 3.4, 0.95, t, sz=13, color=BODY, lnsp=1.05)
        s.end(anim=300 + i * 150)
    s.text(0.55, 5.2, 12.2, 0.4, "ОСНОВА ПРАВИЛ", sz=11, bold=True, color=G2, anim=800)
    for i, t in enumerate(["Закон РУз «О персональных данных»", "Закон РУз «О банковской тайне»", "Внутренние политики ИБ банка"]):
        s.chip(0.55 + i * 4.15, 5.65, 3.95, 0.6, t, fill=MINT, color=DARK, sz=13, anim=850 + i * 100)

    # ---- data traffic light
    s = d.new(bg="flight", notes=(
        "Главный инструмент этого модуля — светофор данных. Зелёный: общедоступная информация — опубликованные тарифы, законы, новости, "
        "а также обезличенные тексты и общие вопросы. Их можно использовать в разрешённых банком ИИ-инструментах. Жёлтый: внутренние "
        "документы и рабочая переписка без персональных данных и тайн. Только в корпоративном ИИ, одобренном банком. Красный: персональные "
        "данные клиентов и сотрудников, банковская тайна, номера карт, пароли и коды, исходный код и настройки систем, неопубликованная "
        "отчётность и стратегия, сведения об инцидентах. Красные данные нельзя передавать ни в какой ИИ вне закрытого контура банка."))
    s.title("«Светофор данных»", anim=0)
    s.subtitle("Перед каждым запросом определите цвет информации", anim=100)
    lights = [("ЗЕЛЁНЫЙ", "можно в разрешённых банком ИИ", "3E9A4E", WHITE,
               ["Опубликованные тарифы, законы, новости", "Обезличенные тексты без привязки к людям", "Общие вопросы: «как вежливо отказать?»",
                "Ваши черновики без данных"]),
              ("ЖЁЛТЫЙ", "только в корпоративном ИИ банка", "F2C94C", DARK,
               ["Внутренние регламенты и инструкции", "Презентации и отчёты для внутреннего пользования", "Рабочая переписка без данных клиентов"]),
              ("КРАСНЫЙ", "никогда — вне закрытого контура банка", "D64545", WHITE,
               ["ФИО, паспорт, ПИНФЛ, телефон, адрес", "Счета, остатки, операции, кредиты", "Номера карт, CVV, пароли, коды из SMS",
                "Исходный код, настройки систем", "Неопубликованная отчётность, стратегия, инциденты"])]
    for i, (h, sub, c, tc, items) in enumerate(lights):
        x = 0.55 + i * 4.15
        s.begin(h)
        card(s, x, 1.95, 3.95, 4.0)
        s.rrect(x, 1.95, 3.95, 1.05, r=0.22, fill=c)
        s.shape(x + 0.22, 2.17, 0.6, 0.6, geom="ellipse", fill=WHITE, line=c, lw=2)
        s.shape(x + 0.36, 2.31, 0.32, 0.32, geom="ellipse", fill=c)
        s.text(x + 1.0, 2.02, 2.8, 0.45, h, sz=17, bold=True, color=tc)
        s.text(x + 1.0, 2.45, 2.8, 0.5, sub, sz=11, color=tc, lnsp=1.0)
        bullets(s, x + 0.3, 3.2, 3.45, 2.65, items, sz=14, spc=7, bcolor=c if i != 1 else "C9A227")
        s.end(anim=200 + i * 200)
    s.rrect(0.55, 6.2, 12.2, 0.7, r=0.25, fill=DARK, text=[{"t": "Не уверены в цвете? Считайте данные **«красными»** и уточните у службы ИБ",
                                                          "bcolor": "FF8A8A"}], sz=15, color=WHITE, align="ctr", anchor="ctr", anim=900)

